// ФАЗОВАЯ РАЗМЕТКА CUTLASS-ФОРВАРДА (kernel_forward.h) для tools/phaseprof.py.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ЗАГОЛОВОК, А НЕ ПРЯМОЙ #include "fmha_phase.h".
// Требование наряда: при маске 0 SASS обязан быть ПОБАЙТОВО прежним. Значит боевая сборка не
// должна видеть инструментальный заголовок ВООБЩЕ -- ни его пломб (prmt = настоящая команда),
// ни его __constant__-символа fmha_phase_never (лишний символ в cubin). Здесь боевой путь
// закрыт заглушками, а настоящий инструмент подключается ТОЛЬКО при FMHA_STRIP_MASK != 0.
//
// ЧЕМ ЗАЩИЩЕНЫ ФАЛЬСИФИКАТОРЫ (мины из наряда).
//   * "компилятор выбросит зависимый код" -- у каждой фазы, чей выход мог бы стать
//     компилятору ИЗВЕСТЕН, стоит НЕ пломба, а ПОДСТАВНОЙ ВЫХОД (FWD_DECOY_ARR): значение
//     непрозрачно (prmt) И РАЗНОЕ у каждого элемента, поэтому CSE не склеивает его в одно
//     (замеренная мина: восемь одинаковых непрозрачных значений -> 9 MUFU.EX2 схлопнулись в 2).
//   * подстановка живёт в ветке `else` конструкции `if constexpr` -- при включённой фазе она
//     НЕ ПОРОЖДАЕТ КОДА, поэтому базовая сборка не платит за оснастку ничего. Именно поэтому
//     пломбы на боевом пути НЕТ: доля фазы считается относительно НЕОСНАЩЁННОЙ базы.
//   * "у выхода не осталось потребителя" (снятый эпилог -> мёртв весь mainloop) лечится
//     FWD_SINK_ARR: предикатная запись по __constant__, которую компилятор обязан сохранить.
//
// ДИАПАЗОН КОДОВ. Маска -- КОМПИЛЯЦИОННАЯ (-DFMHA_STRIP_MASK=<биты>), она не пересекается с
// рантайм-кодами nosc/DIAG (11..15 = DIAG 1..5, 20 = PHSPLIT, 30 = KSP) уже по природе. Если
// маску потребуется прокинуть рантайм-кодом, за форвардом закреплён диапазон 64..127:
// var = 64 + mask, mask = 1..63 (6 фаз). 64..127 свободен: все занятые коды < 32.
#pragma once

#ifndef FMHA_STRIP_MASK
#define FMHA_STRIP_MASK 0u
#endif

#if (FMHA_STRIP_MASK) != 0u
// --- измерительная сборка: настоящий инструмент ---------------------------------------------
#include "fmha_phase.h"
#define FWD_PHASE_ACTIVE 1
#else
// --- боевая сборка: ни одной команды, ни одного символа --------------------------------------
#define FWD_PHASE_ACTIVE 0
#define FMHA_PHASE(name, id) if constexpr (true)
#define FMHA_PHASE_ELSE(name, id) else
#define FMHA_PHASE_ON(id) true
#define FMHA_SEAL_W32(w) ((void)(w))
#define FMHA_SEAL(...) ((void)0)
#define FMHA_SEAL_ARR(a, n) ((void)0)
#define FMHA_SINK(ptr, idx, val) ((void)0)
#endif

// ПОДСТАВНОЙ ВЫХОД: заполняет накопитель значениями, которые (а) компилятору неизвестны,
// (б) РАЗНЫЕ у каждого элемента. Один prmt на весь массив + одно сложение с константой на
// элемент -- дешевле поэлементной пломбы и не даёт CSE схлопнуть массив в одно значение.
#define FWD_DECOY_ARR(arr, n)                                             \
  do {                                                                    \
    float _fwd_b = 1.0f;                                                  \
    FMHA_SEAL_W32(*reinterpret_cast<unsigned*>(&_fwd_b));                 \
    _Pragma("unroll")                                                     \
    for (int _fwd_i = 0; _fwd_i < (int)(n); ++_fwd_i) {                   \
      (arr)[_fwd_i] = _fwd_b + float(_fwd_i) * (1.0f / 4096.0f);          \
    }                                                                     \
  } while (0)

// ПОДСТАВНОЙ ПЕРЕСЧЁТ (для фаз, у которых ВХОД -- чужой выход). Отличается от FWD_DECOY_ARR
// тем, что НЕ ВЫБРАСЫВАЕТ вход: значение остаётся функцией от него, поэтому фаза-поставщик
// не умирает. Мина, на которой это поймано ЗАМЕРОМ (см. таблицу отпечатков): чистая замена
// frag в подстановке софтмакса убила 128 HMMA ПЕРВОГО умножения -- накопитель Q*K^T терял
// последнего потребителя. Правило: замена годится только там, где вход фазы принадлежит ей
// самой (gemm1 читает Q/K, gemm2 читает V/si); везде ещё -- пересчёт.
#define FWD_DECOY_MIX_ARR(arr, n)                                         \
  do {                                                                    \
    float _fwd_b = 1.0f;                                                  \
    FMHA_SEAL_W32(*reinterpret_cast<unsigned*>(&_fwd_b));                 \
    _Pragma("unroll")                                                     \
    for (int _fwd_i = 0; _fwd_i < (int)(n); ++_fwd_i) {                   \
      (arr)[_fwd_i] =                                                     \
          (arr)[_fwd_i] * _fwd_b + float(_fwd_i) * (1.0f / 4096.0f);      \
    }                                                                     \
  } while (0)

// СТОК: держит массив живым, когда его единственный потребитель (эпилог) снят.
// Запись предикатна по __constant__ int, который хост не пишет -- она НЕ ИСПОЛНЯЕТСЯ,
// но компилятор обязан вычислить значения.
#define FWD_SINK_ARR(fptr, arr, n)                                        \
  do {                                                                    \
    _Pragma("unroll")                                                     \
    for (int _fwd_i = 0; _fwd_i < (int)(n); ++_fwd_i) {                   \
      FMHA_SINK((fptr), _fwd_i, (arr)[_fwd_i]);                           \
    }                                                                     \
  } while (0)
