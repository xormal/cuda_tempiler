def mio_calibration_pair(kernel_name):
    """-> (ЗАМЕР, МОДЕЛЬНАЯ НОМИНАЛЬНАЯ, откуда) для ядра из data/calib/*.json.

    ПОЧЕМУ ПАРОЙ, А НЕ ОДНИМ ЧИСЛОМ.  Множитель конфликтности -- это ОТНОШЕНИЕ замера к
    номинальной ставке НА ТОМ ЖЕ УЧАСТКЕ, где замер снят.  Если взять замер оттуда, а номинал
    пересчитать по ДРУГОМУ телу (например, по обеим ролям вместо одной фазы), отношение
    поедет: на volta_fwd_ws это давало x1.511 вместо замеренных x1.185 и завышало возвратимую
    конфликтами долю с 15.6 % до 33.8 % при ЗАМЕРЕННЫХ 19.4 %.
    """
    dirs = [
        os.path.join(_ROOT, "data", "calib"),
        os.path.join(_ROOT, "tempo", "plugins", "sm70", "data", "calib"),
    ]
    files = [(d, f) for d in dirs if os.path.isdir(d) for f in sorted(os.listdir(d))]
    best = None
    for d, f in files:
        if not f.endswith(".json"):
            continue
        rec = json.load(open(os.path.join(d, f), encoding="utf-8"))
        if rec.get("kind") != "wf_per_inst":
            continue
        for row in (rec.get("payload") or {}).get("rows", []):
            key = row["kernel"].split(" ")[0]
            if key and key in (kernel_name or "") and row.get("model_nominal"):
                cand = (
                    row["measured"],
                    row["model_nominal"],
                    "%s / %s" % (rec["id"], row["kernel"]),
                )
                if best is None or len(key) > len(best[2]):
                    best = cand
    return best or (None, None, None)


def analyse(args, out=print):
    body = load_body(args)
    mio_wf = mio_nom = None
    if args.calib:
        mio_wf, mio_nom, src = mio_calibration_pair(body.label)
        if mio_wf:
            out(
                "  КАЛИБРОВКА: цена команды разделяемой памяти взята ИЗ ЗАМЕРА (%s): %.3f "
                "вайвфронта против номинальной ставки модели %.3f на том же участке"
                % (src, mio_wf, mio_nom)
            )
        else:
            out(
                "  КАЛИБРОВКА ЗАПРОШЕНА, НО ЗАПИСИ ДЛЯ ЭТОГО ЯДРА НЕТ -- ставка MIO остаётся "
                "интервалом [нижняя, номинальная]. Это НЕ ошибка, это отсутствие замера."
            )
    chan = channel_table(body, mio_wf, mio_nom, args.l2_hit)
    ins = body.all_ins()
    lim = getattr(args, "rec_limit", None) or REC_LIMIT
    rec = T.rec_mii(len(ins), T.dep_graph(ins), limit=lim) if len(ins) <= lim else 0.0
    verdict = decide(chan, rec, len(ins), lim)
    pads = None
    if args.pad:
        lo, hi = (int(x) for x in args.pad.split(".."))
        pads = range(lo, hi + 1)
    props = [
        rule_R1_homogeneous(body, chan, body.warps),
        rule_R2_sfu(body, chan),
        rule_R3_banks(body, chan, mio_wf, mio_nom, args.lanemap, args.stride, pads),
        rule_R4_regs(body, chan, body.warps),
        rule_R6_streams(body, chan, contiguous=(False if args.interlaced else None)),
        rule_R7_amortize_m(
            body, chan, mb=args.mb, host_hmma=args.host_hmma, warps=body.warps
        ),
        rule_R8_fold_constants(body, chan, bits=args.bits),
        rule_R9_schedule(body, chan),
        rule_R10_shadow_pack(body, chan),
        rule_R5_name(verdict, chan),
    ]
    report(
        body,
        chan,
        verdict,
        props,
        body.warps,
        out=out,
        listing=getattr(args, "inventory", 0),
    )
    ph = None
    if args.host_hmma:
        ph = phase_report(body, chan, body.warps, args.host_hmma, out=out)
        out("  " + BOUND_LINE)
    return {"body": body, "chan": chan, "verdict": verdict, "props": props, "phase": ph}


