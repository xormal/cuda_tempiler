class SpeedupFromModel(RuntimeError):
    """Отказ, а не число.  Возбуждается там, где кто-то попробует получить из модели время."""


def speedup_from_bound(before, after, kind="расписание", time_before=None):
    """ИСПОЛНЯЕМЫЙ ЗАПРЕТ: ожидаемое ускорение из модели НЕ ВЫДАЁТСЯ, выдаётся ОТКАЗ.

    Функция заведена НЕ для того, чтобы её звали, а для того, чтобы её НЕЛЬЗЯ было обойти
    молча: запрет, записанный только прозой (docs/NOT_YET.md §3-бис), исполняется ровно до
    первого, кто напишет `t * a / b` своей рукой.  Здесь это падение с причиной и с числом.

    ЗАПРЕТ НАКРЫВАЕТ ОБЕ ВЕТВИ ЗАКОНА, и это не перестраховка, а вторая замеренная точка:
    ветвь РАСПИСАНИЯ завысила выигрыш втрое (0.984 против 0.885), ветвь ПЕРИОДА (канальная)
    -- на 19 % (x1.50 против x1.222, reports/EV_accum_spill.md §2.4).  Оба раза в ОДНУ
    сторону: модель оптимистична.  Разрешить одну ветвь и запретить другую значило бы
    запретить не то, что ошибается, а то, что попалось.
    """
    raise SpeedupFromModel(
        "%s (запрошено по величине «%s»: %s -> %s%s)"
        % (
            NO_SPEEDUP_LINE,
            kind,
            before,
            after,
            "" if time_before is None else " при замеренном времени %s" % time_before,
        )
    )


def speedup_from_sched(sched_before, sched_after, time_before=None):
    """То же по ветви РАСПИСАНИЯ.  Отдельное имя -- чтобы отказ называл ветвь, а не «модель»."""
    return speedup_from_bound(sched_before, sched_after, "расписание", time_before)


