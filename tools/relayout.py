def selftest(out=print):
    ok = bad = skip = 0

    def chk(label, cond, detail=""):
        nonlocal ok, bad
        out(
            "  %-9s %s%s"
            % ("ПРОЙДЕН" if cond else "ПАДЁТ", label, ("  " + detail) if detail else "")
        )
        if cond:
            ok += 1
        else:
            bad += 1

    out("САМОПРОВЕРКА ПЕРЕУКЛАДЧИКА (карта не нужна)")

    # ЯКОРЬ 1. Арифметика каналов на теле, посчитанном РУКОЙ.
    # 10 команд ALU (2.00 такта) + 8 команд FPU (2.00) = ALU 20, FPU 16, ВЫДАЧА 18 при 4 варпах
    # (варпов на планировщик = 1).  Это ровно состав боевой цепочки int12 (§3 отчёта).
    if os.path.exists(INT12_SASS):
        name, ins = _bodies_from_sass(INT12_SASS, "k_sass_magic")
        body = Body(name, [(None, ins, 4)], 4, "цепочка счёта")
        ch = channel_table(body)
        chk(
            "1. арифметика каналов (ручной счёт)",
            len(ins) == 18
            and abs(ch["ALU"].hi - 20) < 1e-6
            and abs(ch["FPU"].hi - 16) < 1e-6
            and abs(ch["ISSUE"].hi - 18) < 1e-6,
            "команд %d, ALU %.0f, FPU %.0f, ВЫДАЧА %.0f"
            % (len(ins), ch["ALU"].hi, ch["FPU"].hi, ch["ISSUE"].hi),
        )
        # ЯКОРЬ 2. Разбор совпадает с РУЧНЫМ счётом отчёта §3: 6 / 18 / 25 команд.
        counts = {}
        for pat, exp in (("k_sass_i8", 6), ("k_sass_magic", 18), ("k_sass_i2f", 25)):
            counts[pat] = len(_bodies_from_sass(INT12_SASS, pat)[1])
        chk(
            "2. разбор против ручного счёта §3",
            counts == {"k_sass_i8": 6, "k_sass_magic": 18, "k_sass_i2f": 25},
            str(counts),
        )
        # ЯКОРЬ 3. ФАЗОВОЕ ПРЕДСКАЗАНИЕ против 8 ЗАМЕРЕННЫХ точек.
        # ЧТО ЗДЕСЬ ЧЕСТНО, А ЧТО НЕТ: коридор ставки слота (0.093-0.154) получен ИЗ ЭТОГО ЖЕ
        # замера, поэтому попадание -- НЕ независимое предсказание.  Независимой является ФОРМА
        # закона: цена ЛИНЕЙНА по числу команд и НЕ зависит ни от трубы, ни от плотности.  Именно
        # её и проверяют восемь точек: одна ставка, два маршрута с РАЗНЫМ составом (18 команд
        # против 25, из них 8 конверсий), четыре плотности -- и ни одна точка не вне коридора.
        out_of = []
        for route, pat, col in (("магия", "k_sass_magic", 0), ("I2F", "k_sass_i2f", 1)):
            _, ins2 = _bodies_from_sass(INT12_SASS, pat)
            for u, meas in INT12_MEASURED.items():
                b = Body("x", [(None, ins2 * u, INT12_WARPS)], INT12_WARPS, "фаза")
                c2 = channel_table(b)
                p = phase_report(b, c2, INT12_WARPS, INT12_HMMA, out=lambda *_: None)
                m = (meas[col] - 1.0) * 100.0
                if not (p["pred_lo"] - 0.05 <= m <= p["pred_hi"] + 0.05):
                    out_of.append(
                        "%s U=%d: замер %+.1f, коридор %+.1f..%+.1f"
                        % (route, u, m, p["pred_lo"], p["pred_hi"])
                    )
        chk(
            "3. фазовый коридор против 8 замеренных точек",
            not out_of,
            "вне коридора: %s" % ("нет" if not out_of else "; ".join(out_of)),
        )
        # ЯКОРЬ 4. ФАЛЬСИФИКАТОР СТАВКИ: если конверсии считать по 8.00 такта (ставка SFU),
        # модель обязана НАРУШИТЬ собственный замер.  Проверяем, что нарушила бы, -- и потому
        # эта ставка к конверсиям НЕ ПРИМЕНЯЕТСЯ.
