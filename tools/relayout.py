def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "obj", nargs="?", help="lib.so | cubin | текст cuobjdump (с --sass)"
    )
    ap.add_argument("--kernel", help="образец имени ядра")
    ap.add_argument(
        "--sass", action="store_true", help="вход -- ТЕКСТ cuobjdump, а не бинарь"
    )
    ap.add_argument(
        "--warps",
        type=int,
        default=None,
        help="варпов на SM (по умолчанию 8; при ролях -- сумма варпов ролей ИЗ ТЕЛА)",
    )
    ap.add_argument(
        "--roles",
        action="store_true",
        help="развести варпы по ролям и сложить нагрузки",
    )
    ap.add_argument(
        "--core", action="store_true", help="только БЕЗУСЛОВНЫЙ остов цикла"
    )
    ap.add_argument(
        "--whole", action="store_true", help="взять ВСЁ тело ядра, а не мейнлуп"
    )
    ap.add_argument(
        "--strip-io",
        action="store_true",
        dest="strip_io",
        help="оставить только цепочку счёта (снять память, адресный срез, инварианты)",
    )
    ap.add_argument(
        "--calib", action="store_true", help="взять цену команды разделяемой из ЗАМЕРА"
    )
    ap.add_argument(
        "--l2-hit",
        type=float,
        default=None,
        dest="l2_hit",
        help="доля попаданий L2 в процентах (ЗАМЕР). Без неё канал DRAM -- интервал",
    )
    ap.add_argument(
        "--host-hmma",
        type=int,
        default=None,
        dest="host_hmma",
        help="РЕЖИМ ФАЗЫ: тензорных команд на варп в цикле-хозяине",
    )
    ap.add_argument(
        "--mb",
        type=int,
        default=None,
        help="плитка по M в единицах формы тензорной операции (для R7)",
    )
    ap.add_argument(
        "--bits",
        type=int,
        default=None,
        help="разрядность кода веса (для R8: нижняя граница -- функция разрядности)",
    )
    ap.add_argument(
        "--interlaced",
        action="store_true",
        help="доступ ЧЕРЕССТРОЧНЫЙ, а не сплошной (для R6)",
    )
    ap.add_argument("--lanemap", help="карта полос rowbase от номера полосы l (для R3)")
    ap.add_argument("--stride", type=int, help="шаг строки В СЛОВАХ (для R3)")
    ap.add_argument("--pad", help="диапазон дополнений, напр. 0..12")
    ap.add_argument(
        "--rec-limit",
        type=int,
        default=None,
        dest="rec_limit",
        help="порог размера тела для RecMII (умолчание %d; цена %s)"
        % (REC_LIMIT, REC_COST_NOTE),
    )
    ap.add_argument("--json", help="сложить разбор в файл")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument(
        "--gate", action="store_true", help="гейт годности на трёх замеренных телах"
    )
    ap.add_argument(
        "--gate-sched",
        action="store_true",
        dest="gate_sched",
        help="ГЕЙТ ГОДНОСТИ ПРАВИЛА R9 на трёх телах с ЗАМЕРЕННОЙ долей трубы",
    )
    ap.add_argument(
        "--gate-pack",
        action="store_true",
        dest="gate_pack",
        help="ГЕЙТ ГОДНОСТИ УКЛАДЧИКА R10 на ЧЕТЫРЁХ телах (включая то, где ХУЖЕ)",
    )
    ap.add_argument(
        "--gate-regs",
        action="store_true",
        dest="gate_regs",
        help="ГЕЙТ ГОДНОСТИ ПРАВИЛА R4 на ПЯТИ телах с известными числами ptxas",
    )
    ap.add_argument(
        "--gate-rank",
        action="store_true",
        dest="gate_rank",
        help="ГЕЙТ «РАНГ, А НЕ ВЕЛИЧИНА» на ДЕВЯТИ телах с замеренным временем",
    )
    ap.add_argument(
        "--inventory",
        type=int,
        nargs="?",
        const=40,
        default=0,
        help="напечатать ПЕРЕЧЕНЬ остатка (сколько строк; умолчание 40)",
    )
    args = ap.parse_args()

    if args.selftest:
        return selftest()
    if args.gate_sched:
        return gate_sched()[0]
    if args.gate_pack:
        return gate_pack()[0]
    if args.gate_regs:
        return gate_regs()[0]
    if args.gate_rank:
        return gate_rank()[0]
    if args.gate:
        # ДВА ГЕЙТА, А НЕ ОДИН: первый спрашивает «назван ли ТОТ ЖЕ связывающий канал», второй --
        # «различены ли тела, которые каналами НЕ различаются». Второй заведён ровно потому, что
        # первый прошёл 3/3 и при этом молчал на паре тел с разницей времени в 1.20 раза.
        rc1 = gate()
        print("")
        rc2 = gate_sched()[0]
        print("")
        rc3 = gate_pack()[0]
        print("")
        rc4 = gate_regs()[0]
        print("")
        rc5 = gate_rank()[0]
        return 1 if (rc1 or rc2 or rc3 or rc4 or rc5) else 0
    if args.lanemap and not args.obj:
        # РЕЖИМ БЕЗ ТЕЛА: только правило R3 -- конфликтность по карте полос, до всякой сборки.
        pads = range(0, 16)
        if args.pad:
            lo, hi = (int(x) for x in args.pad.split(".."))
            pads = range(lo, hi + 1)
        rows = BF.sweep(BF.rows_from_lanemap(args.lanemap), args.stride, pads)
        print(
            "R3 КОНФЛИКТНОСТЬ БАНКОВ по карте полос %r, шаг %d слов"
            % (args.lanemap, args.stride)
        )
        print("  %4s %5s %14s  %s" % ("pad", "S", "конфликтность", "разных банков"))
        for pad, S, c, img in rows:
            print("  %4d %5d %14.2f  %d" % (pad, S, c, len(img)))
        best = min(rows, key=lambda r: (r[2], r[0]))
        print(
            "  МИНИМУМ %.2f при дополнении %d слов (S=%d)."
            % (best[2], best[0], best[1])
        )
        print("  " + BOUND_LINE)
        return 0
    if not args.obj:
        ap.error("нужен путь к телу, либо --selftest / --gate / --lanemap")
    res = analyse(args)
    if args.json:
        st = schedule_stats(sched_part(res["body"])[1])
        with open(args.json, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "тело": res["body"].label,
                    "команд": res["body"].n,
                    "каналы": {c: [l.lo, l.hi] for c, l in res["chan"].items()},
                    "вердикт": res["verdict"].kind,
                    "связывает": res["verdict"].channel,
                    "ResMII": res["verdict"].resmii,
                    "RecMII": res["verdict"].recmii,
                    # РАСПИСАНИЕ кладётся в выгрузку ЦЕЛИКОМ: именно по нему сравниваются две
                    # сборки ДО и ПОСЛЕ правки, и делать это глазами по печати -- значит терять
                    # ровно ту величину, ради которой правило заведено.
                    "расписание": None
                    if st is None
                    else {
                        "тактов": st["sched"],
                        "тензорный_пол": st["floor"],
                        "запас": st["slack"],
                        "доля_трубы_предсказание": pipe_share(st["slack"]),
                        "доля_трубы_коридор": [
                            pipe_share(st["slack"], PIPE_K_LO),
                            pipe_share(st["slack"], PIPE_K_HI),
                        ],
                        "длиннейшая_нетензорная_серия": st["run"],
                        "по_классам": {
                            k: {"команд": c, "тактов": s}
                            for k, (c, s) in st["by"].items()
                        },
                        "избыток_над_дном": st["surplus"],
                        "reuse_самопроверка": [st["reuse_ok"], st["reuse_n"]],
                        # ГЛАВНЫЙ ПОКАЗАТЕЛЬ и второй вход -- в выгрузку тоже: сравнение ДО/ПОСЛЕ
                        # правки ведётся по ним, а не по сумме.
                        "в_тени": [st["shadow"], st["non_n"]],
                        "доля_в_тени": st["shadow_frac"],
                        "вне_тени": st["non_n"] - st["shadow"],
                        "закрытая_форма": st["closed"],
                        "закрытая_форма_ошибка": st["closed"] / st["sched"] - 1.0,
                        "опкоды_по_пространствам": dict(st["space"]),
                    },
                    "фаза": res["phase"],
                    "оговорка": BOUND_LINE,
                },
                f,
                ensure_ascii=False,
                indent=1,
            )
    return 0


if __name__ == "__main__":
    sys.exit(main())
