class Body(object):
    """Часть работы, повторяющаяся с периодом T.  Может состоять из НЕСКОЛЬКИХ РОЛЕЙ.

    parts -- [(имя роли | None, [Ins], варпов этой роли)].  Роли складываются: варпы обеих
    ролей висят на ОДНИХ И ТЕХ ЖЕ четырёх планировщиках, поэтому брать максимум по ролям --
    занижение (tools/tempo.py §3c).
    """

    def __init__(self, label, parts, warps, how, cfg=None):
        self.label = label
        self.parts = parts
        self.warps = warps
        self.how = how  # человекочитаемое: что именно взято за итерацию
        self.n = sum(len(p[1]) for p in parts)
        # ГРАФ УПРАВЛЕНИЯ, а не только команды.  Без него причина «команда лежит в основном
        # блоке БЕЗ тензорных команд» неотличима от «зависимость», а лечения у них РАЗНЫЕ:
        # первая правится исходником, вторая -- поворотом цепи.  У тела, собранного не из
        # машинного кода, cfg нет, и правило R10 обязано ОТКАЗАТЬ, а не подставить ноль.
        self.cfg = cfg

    def all_ins(self):
        return [it for _, ins, _ in self.parts for it in ins]


def _read_text(path):
    """Текст разборки; .gz читается прозрачно и БАЙТ В БАЙТ тем же содержимым.

    Сжатие тут не удобство, а условие хранения: три тела разбора занимают 1.9 МБ текста и
    0.12 МБ сжатыми.  Никакого преобразования содержимого при этом не происходит -- иначе
    хранился бы уже НЕ вывод cuobjdump, и сверять было бы не с чем.
    """
    if path.endswith(".gz"):
        import gzip

        with gzip.open(path, "rt", encoding="utf-8", errors="ignore") as f:
            return f.read()
    return open(path, encoding="utf-8", errors="ignore").read()


def _kernels_from(path, as_sass):
    if as_sass:
        return IS.parse_sass(_read_text(path))
    return T.load_kernels(path)


def strip_io(ins):
    """ЦЕПОЧКА СЧЁТА без обвеса: убрать обращения к памяти, АДРЕСНЫЙ СРЕЗ, инварианты и хвост.

    Правило дословно повторяет ручной счёт reports/EV_int12_prim.md §3 ("из счёта исключены
    загрузка/выгрузка/адресная арифметика/EXIT; IMAD.MOV на константы вынесен отдельно"), и
    якорь selftest проверяет, что автоматический разбор даёт ТЕ ЖЕ 6 / 18 / 25 команд.
    Адресный срез берётся готовой функцией плагина -- своего закона тут не вводится.
    """
    cfg = IS.CFG(ins)
    sl = set(IS.address_slice(cfg, set(cfg.blocks)))
    out, dropped = [], collections.Counter()
    for it in ins:
        if it.cls in MEM_CLS or it.cls in ("загр.разд", "зап.разд", "разлив"):
            dropped["обращения к памяти"] += 1
            continue
        if it.base in ("EXIT", "BRA", "NOP", "S2R", "BSSY", "BSYNC", "BMOV"):
            dropped["управление/хвост"] += 1
            continue
        if it.addr in sl:
            dropped["адресный срез"] += 1
            continue
        srcs = [s for s in it.srcs if re.match(r"^R\d+$", s) and s != "RZ"]
        if not srcs:
            dropped["инвариант (материализация константы)"] += 1
            continue
        out.append(it)
    return out, dict(dropped)


def load_body(args):
    kern = _kernels_from(args.obj, args.sass)
    names = sorted(k for k in kern if not args.kernel or re.search(args.kernel, k))
    if not names:
        raise SystemExit(
            "ядро по образцу %r не найдено (всего ядер %d)" % (args.kernel, len(kern))
        )
    name = names[0]
    if len(names) > 1:
        # НЕ МОЛЧА: разобрать не то тело и не заметить -- самый дешёвый способ получить
        # уверенный неверный вердикт. Образец обязан быть однозначным.
        print(
            "  ВНИМАНИЕ: образцу подошло %d ядер, взято ПЕРВОЕ (%s). Уточните --kernel."
            % (len(names), name[:70])
        )
    ins_all = kern[name]
    cfg = IS.CFG(ins_all)

    # РОЛИ.  У боевого форварда варпы разведены на везущих и считающих: РАЗНЫЕ тела, ОДИН период.
    roles = IS.detect_roles(cfg) if args.roles else None
    if roles and roles.names:
        parts, warps = [], 0
        for rn in roles.names:
            ml = IS.pick_mainloop(cfg, roles.blocks[rn])
            if ml is None:
                continue
            sel = T.core_blocks(cfg, ml[0], ml[1], ml[2]) if args.core else ml[1]
            parts.append(
                (
                    rn,
                    [it for a in sorted(sel) for it in cfg.blocks[a]],
                    roles.warps[rn] or 0,
                )
            )
            warps += roles.warps[rn] or 0
        if parts:
            # ЗАНЯТОСТЬ БЕРЁТСЯ ИЗ САМОГО ТЕЛА, а не из умолчания: роли объявляют, сколько
            # варпов у каждой, и подменять это числом «8 по умолчанию» -- значит считать
            # нагрузку не того ядра.  Ключ --warps остаётся и перекрывает.
            return Body(
                name,
                parts,
                args.warps or warps,
                "мейнлуп КАЖДОЙ РОЛИ, нагрузки сложены (%s); %s"
                % (", ".join("%s x%d" % (p[0], p[2]) for p in parts), roles.note),
                cfg,
            )

    w = args.warps or 8
    ml = T.mainloop_ins(cfg, core=args.core)[0]
    if ml and not args.whole:
        return Body(
            name,
            [(None, ml, w)],
            w,
            "мейнлуп (естественный цикл с наибольшим числом тензорных команд)",
            cfg,
        )

    ins = ins_all
    how = "ВСЁ ТЕЛО ЯДРА (мейнлупа нет либо запрошено --whole): за итерацию принят один вызов"
    if args.strip_io:
        ins, dropped = strip_io(ins)
        how = "ЦЕПОЧКА СЧЁТА (--strip-io: снято %s)" % ", ".join(
            "%s %d" % (k, v) for k, v in sorted(dropped.items())
        )
    return Body(name, [(None, ins, w)], w, how, cfg)


