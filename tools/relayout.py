def sched_class(it):
    return SCHED_CLASS.get(it.cls, SCHED_CLASS_DEFAULT)


def longest_nontensor_run(ins):
    """Самая длинная НЕПРЕРЫВНАЯ серия нетензорных команд -- это ДИАГНОЗ, а не метрика.

    Пока варп проходит серию, его тензорная труба стоит.  Дыру в 3 команды второй варп на
    планировщике закрывает полностью, дыру в 92 -- не закрывает никак, и никакая занятость
    этого не чинит.  Число берётся из ПОРЯДКА команд, а не из их счёта: у двух тел разбора
    счёт нетензорных отличается на 7 %, а серия -- в 30 раз (92 против 3).
    """
    best = cur = 0
    for it in ins:
        if it.cls == IS.TENSOR:
            cur = 0
        else:
            cur += 1
            best = max(best, cur)
    return best


def space_audit(ins):
    """ЧЕТВЁРТОЕ ЧИСЛО «СКОМПИЛИЛ -- ПРОВЕРЬ»: ОПКОД ОБРАЩЕНИЯ, а не только регистры/разлив/кадр.

    Смена пространства адресов не отражается НИ В ОДНОМ отчёте компилятора: он молчит и про
    разлив не соврёт, а про то, что подача фрагмента уехала из разделяемой в общее пространство,
    не скажет ничего.  Признак -- опкод: LDS/STS против LD.E/ST.E при живой разделяемой памяти.
    """
    c = collections.Counter()
    for it in ins:
        if it.base in ("LDS", "LDSM", "STS"):
            c["разделяемая"] += 1
        elif it.base in GENERIC_OPS:
            c["ОБЩЕЕ"] += 1
        elif it.base in ("LDG", "STG"):
            c["глобальная"] += 1
        elif it.base in ("LDL", "STL"):
            c["локальная (разлив)"] += 1
    return c


def schedule_stats(ins):
    """-> dict с длиной статического расписания, или None, если полей управления НЕТ.

    ОТКАЗ, А НЕ НОЛЬ.  Тело, собранное кодом (а не разобранное из машинного), полей задержки
    не несёт, и подставить туда ноль значило бы напечатать запас 1.00 на теле, о расписании
    которого ничего не известно.
    """
    ins = [it for it in ins if getattr(it, "stall", None) is not None]
    if not ins:
        return None
    n = len(ins)
    hmma = sum(1 for it in ins if it.cls == IS.TENSOR)
    sched = float(sum(it.stall for it in ins))
    if sched <= 0:
        return None
    by = collections.OrderedDict()
    for it in ins:
        k = sched_class(it)
        c, s = by.get(k, (0, 0))
        by[k] = (c + 1, s + it.stall)
    floor = TENSOR_ISSUE_RATE * hmma
    non_n = n - hmma
    non_st = sched - by.get("HMMA", (0, 0))[1]
    # ИЗБЫТОК = то, что СВИДЕТЕЛЬ уже показал снимаемым: у нашей сборки CUTLASS каждая
    # нетензорная команда мейнлупа идёт по 1.00 такта.  Это не мечта, а другое тело на том же
    # ptxas.  HMMA сюда НЕ входит: их задержка -- собственный подпор трубы, и он остаётся.
    surplus = max(0.0, non_st - NONTENSOR_STALL_FLOOR * non_n)
    reuse_ok = sum(
        1
        for it in ins
        if bin(getattr(it, "reuse", 0)).count("1") == getattr(it, "nreuse", 0)
    )
    # ТЕНЬ.  Последовательность ЦИКЛИЧЕСКАЯ: за последней командой мейнлупа идёт первая, и
    # считать иначе значит терять один переход из ста пятидесяти. (Линейный счёт даёт у тела
    # CUTLASS 148 из 151 вместо 149 -- та же величина, но занижена ровно на замыкание петли.)
    shadow = sum(
        1
        for i, it in enumerate(ins)
        if it.cls != IS.TENSOR and ins[(i + 1) % n].cls == IS.TENSOR
    )
    h2n = sum(
        1
        for i, it in enumerate(ins)
        if it.cls == IS.TENSOR and ins[(i + 1) % n].cls != IS.TENSOR
    )
    hmma_st = by.get("HMMA", (0, 0))[1]
    closed = TENSOR_ISSUE_RATE * hmma - h2n + non_st
    return {
        "n": n,
        "hmma": hmma,
        "sched": sched,
        "floor": floor,
        "slack": (floor / sched) if sched else 0.0,
        "by": by,
        "run": longest_nontensor_run(ins),
        "non_n": non_n,
        "non_st": non_st,
        "surplus": surplus,
        "sched_floor": sched - surplus,
        "stall_mean": sched / n,
        "reuse_ok": reuse_ok,
        "reuse_n": len(ins),
        # ГЛАВНЫЙ ДИАГНОСТИЧЕСКИЙ ПОКАЗАТЕЛЬ: доля нетензорных команд, стоящих В ТЕНИ тензорной.
        "shadow": shadow,
        "shadow_frac": (float(shadow) / non_n) if non_n else 0.0,
        "shadow_room": min(
            non_n, hmma
        ),  # сколько ВООБЩЕ может быть скрыто: теней не больше HMMA
        "h2n": h2n,
        "hmma_st": hmma_st,
        "closed": closed,
        "closed_hmma": TENSOR_ISSUE_RATE * hmma - h2n,
        "space": space_audit(ins),
    }


