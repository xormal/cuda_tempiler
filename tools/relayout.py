def regs_need(ins, wide=True, budget=None):
    """ТРЕБУЕМЫЕ РЕГИСТРЫ по машинному коду -> dict.  Карта не нужна, сборка не нужна.

    R_треб = MaxLive + РАЗЛИТОЕ + REG_OVERHEAD, и все три слагаемых читаются из тела:

      * MaxLive -- живость ЦИКЛИЧЕСКОГО тела, считанная ПО ШИРИНЕ операнда, а не по числу
        имён (см. SCH.live_cyclic и IS.reg_span);
      * РАЗЛИТОЕ -- слов, уехавших в локальную память.  Это НЕ поправка на компилятора и не
        подгонка: машинный код тела, которое УЖЕ РАЗЛИЛО, читается УЖЕ ОБЛЕГЧЁННЫМ -- разлитое
        значение в регистре больше не живёт, поэтому его MaxLive ЗАНИЖЕН РОВНО НА РАЗЛИТОЕ.
        Свидетель прямо в наборе: у KSTEPS=8 живость МЕНЬШЕ, чем у KSTEPS=1 (239 против 244),
        хотя работы у него строго больше.  Величина берётся из ОПКОДОВ (STL и их слоты), а не
        из отчёта компилятора; для тела, которого ещё нет, она РАВНА НУЛЮ, и модель остаётся
        предсказательной;
      * REG_OVERHEAD = 7 -- ЗАМЕРЕННЫЙ (tools/probe.cu, лестница c1xNP) расход сверх живости.
        Он снят на СКАЛЯРНОМ теле, где имя и ширина совпадают, поэтому поправка на ширину его
        НЕ ЗАТРАГИВАЕТ.

    ПОЧЕМУ ПОРОГ «>= бюджета», А НЕ «> бюджета».  Считанная величина -- потребность ОДНОГО
    МЕЙНЛУПА, а сборщик распределяет регистры на ВСЁ ядро: прологу нужен хотя бы один регистр
    сверх (он обязан посчитать адреса, с которых мейнлуп начнёт).  Значит «мейнлуп один занимает
    ВЕСЬ файл» уже означает, что ядру файла не хватит.  Это не подгонка порога, а прочтение
    того, что модель на самом деле посчитала: НИЖНЮЮ оценку потребности ядра.

    ОТСЮДА ЖЕ -- АСИММЕТРИЯ ВЫВОДА, и её надо называть вслух: «РАЗОЛЬЁТСЯ» -- вывод СТРОГИЙ
    (нижняя оценка уже превысила потолок), «влезает» -- условный («мейнлуп не мешает»).

    wide=False -- ПРЕЖНЯЯ редакция (счёт ИМЁН).  Оставлена не из вежливости: гейт обязан
    показывать, что прежний способ его ПРОВАЛИВАЕТ, иначе гейт не проверяет ничего.
    """
    budget = T.REG_ISA_LIMIT if budget is None else budget
    ml = (
        SCH.live_cyclic(ins, wide=wide)
        if hasattr(SCH, "live_cyclic")
        else SCH.max_live(ins, list(range(len(ins))), len(ins))
    )
    sp = IS.spill_words(ins) if (wide and hasattr(IS, "spill_words")) else 0
    need = ml + sp + T.REG_OVERHEAD
    return {
        "maxlive": ml,
        "spill": sp,
        "need": need,
        "budget": budget,
        "verdict": "РАЗОЛЬЁТСЯ" if need >= budget else "влезает",
        # ВТОРОЙ, НЕЗАВИСИМЫЙ СВИДЕТЕЛЬ, и он в вердикт НЕ входит намеренно: опкод LDL/STL
        # означает, что сборщик УЖЕ сказал «не влезло», и подставить его в вердикт значило бы
        # выдать чужой ответ за свой.  Он печатается рядом -- чтобы сверять, а не заменять.
        "witness": sp > 0,
    }


