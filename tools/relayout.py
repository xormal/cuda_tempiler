def schedule_block(body, out=print, listing=0):
    """1b. РАСПИСАНИЕ: то, чем тела различаются, когда счёт команд их НЕ различает.

    Печатается ДО вердикта намеренно.  Вердикт о канале может быть «МОДЕЛЬ МОЛЧИТ» -- и это
    честно, каналы действительно не расходятся; но читатель обязан увидеть рядом величину,
    которая расходится в 1.26 раза на тех же телах.
    """
    role, ins = sched_part(body)
    st = schedule_stats(ins)
    out(
        "  1b. ДЛИНА СТАТИЧЕСКОГО РАСПИСАНИЯ (поля управления машинного кода, ТОЛЬКО ЧТЕНИЕ)"
    )
    if st is None:
        out(
            "     ОТКАЗ: поля задержки не прочитаны (тело собрано не из машинного кода). "
            "Ноль сюда не подставляется."
        )
        out("")
        return None
    out(
        "     самопроверка разборщика: разряды reuse против текстового '.reuse' -- %d из %d%s"
        % (
            st["reuse_ok"],
            st["reuse_n"],
            ""
            if st["reuse_ok"] == st["reuse_n"]
            else "  <== РАСХОЖДЕНИЕ, полям не верить",
        )
    )
    if st["hmma"]:
        out(
            "     расписание %.0f тактов | тензорный пол %.0f (%d HMMA x %.2f) | ЗАПАС %.3f"
            % (st["sched"], st["floor"], st["hmma"], TENSOR_ISSUE_RATE, st["slack"])
        )
        out(
            "     ПРЕДСКАЗАННАЯ ДОЛЯ ТЕНЗОРНОЙ ТРУБЫ %.1f %% (коридор %.1f..%.1f по разбросу "
            "коэффициента 0.804-0.818 на трёх замеренных телах)"
            % (
                pipe_share(st["slack"]),
                pipe_share(st["slack"], PIPE_K_LO),
                pipe_share(st["slack"], PIPE_K_HI),
            )
        )
    else:
        out(
            "     расписание %.0f тактов на %d команд (%.2f такта на команду); тензорных команд "
            "нет -- доля трубы не предсказывается"
            % (st["sched"], st["n"], st["stall_mean"])
        )
    if st["hmma"]:
        out(
            "     НЕТЕНЗОРНЫХ В ТЕНИ ТЕНЗОРНОЙ: %d из %d = %.1f %%  <== ГЛАВНЫЙ ПОКАЗАТЕЛЬ "
            "(достижимо 98.7 %%, замер на теле-свидетеле)"
            % (st["shadow"], st["non_n"], 100.0 * st["shadow_frac"])
        )
        # ПОЛ УКЛАДКИ ЧИТАЕТСЯ ПО РЕЖИМУ, А НЕ ПО УМОЛЧАНИЮ (LAW=L-SHADOW-REGIME-DECIDES-LEVER).
        _реж, _rt, _пол, _рычаг = shadow_regime(st["hmma"], st["non_n"])
        out(
            "        теней всего %d (по числу тензорных); РЕЖИМ %s -- %s. %s"
            % (
                st["hmma"],
                _реж,
                _рычаг,
                "При полном перемежении расписание = тензорный пол %.0f, доля трубы %.1f %%"
                % (st["floor"], pipe_share(1.0))
                if _пол is None
                else "Ниже %d (канал ВЫДАЧИ) не опустит НИКАКАЯ укладка; тензорный пол %.0f "
                "здесь недостижим по построению" % (_пол, st["floor"]),
            )
        )
        # ЦЕНА ОДНОЙ НЕПРИКРЫТОЙ КОМАНДЫ.  Превышение над тензорным полом несут именно те
        # нетензорные, которым тени не досталось; их счёт -- та величина, которую двигает приём.
        # На восьми телах разбора отношение держится около 2.4 такта на неприкрытую команду.
        naked = st["non_n"] - st["shadow"]
        if naked > 0:
            out(
                "        ВНЕ ТЕНИ %d команд; превышение над полом %.0f тактов = %.2f такта на "
                "неприкрытую команду -- ЭТО и есть величина, которую двигает приём"
                % (
                    naked,
                    st["sched"] - st["floor"],
                    (st["sched"] - st["floor"]) / naked,
                )
            )
        out(
            "     ЗАКРЫТАЯ ФОРМА (второй, независимый вход): 2*%d - %d + %.0f = %.0f против "
            "замеренных %.0f (%+.2f %%); тензорная часть предсказана ПОРЯДКОМ: %.0f против %.0f"
            % (
                st["hmma"],
                st["h2n"],
                st["non_st"],
                st["closed"],
                st["sched"],
                100.0 * (st["closed"] / st["sched"] - 1.0),
                st["closed_hmma"],
                st["hmma_st"],
            )
        )
    out(
        "     САМАЯ ДЛИННАЯ НЕПРЕРЫВНАЯ НЕТЕНЗОРНАЯ СЕРИЯ: %d команд  <== это ПРИЧИНА, а не метрика"
        % st["run"]
    )
    sp = st["space"]
    if sp:
        warn = (
            "  <== ОБЩЕЕ ПРОСТРАНСТВО ПРИ ЖИВОЙ РАЗДЕЛЯЕМОЙ: признак пространства потерян?"
            if (sp.get("ОБЩЕЕ") and sp.get("разделяемая"))
            else ""
        )
        out(
            "     ОПКОД ОБРАЩЕНИЯ (четвёртое число «скомпилил -- проверь»): %s%s"
            % (", ".join("%s %d" % (k, v) for k, v in sorted(sp.items())), warn)
        )
    out(
        "     задержка ПО КЛАССАМ команд (куда смотреть; дно 1.00 такта ЗАМЕРЕНО на теле-свидетеле)"
    )
    out(
        "        %-10s %8s %10s %10s %10s"
        % ("класс", "команд", "тактов", "на команду", "избыток")
    )
    for k, (c, s) in sorted(st["by"].items(), key=lambda kv: -kv[1][1]):
        extra = (
            "" if k == "HMMA" else "%10.0f" % max(0.0, s - NONTENSOR_STALL_FLOOR * c)
        )
        out(
            "        %-10s %8d %10.0f %10.2f %s"
            % (k, c, s, s / float(c), extra or "%10s" % "--")
        )
    tail = ""
    if st["hmma"]:
        sl2 = st["floor"] / max(st["sched_floor"], 1e-9)
        tail = ", запас %.3f, доля трубы %.1f %%" % (sl2, pipe_share(sl2))
    out(
        "     ИЗБЫТОК нетензорных над дном: %.0f тактов из %.0f -> расписание %.0f%s"
        % (st["surplus"], st["non_st"], st["sched_floor"], tail)
    )
    out("")
    inventory_block(body, out=out, listing=listing)
    return st


def inventory_block(body, out=print, listing=0):
    """1c. ОПИСЬ ОСТАТКА: кто НЕ в тени и ПОЧЕМУ (задача 135).

    ЗАЧЕМ РЯДОМ С 1b.  Раздел 1b печатает ДОЛЮ («в тени 25.9 %»), и по доле нельзя решить, что
    делать: она одинаково выглядит и когда мест не хватило, и когда места есть, а укладчик не
    дотянулся.  Здесь печатается СЧЁТ МЕСТ и ПЕРЕЧЕНЬ непоставленного с причиной -- то есть
    ровно то, из чего следует ход.
    """
    role, ins = sched_part(body)
    cfg = getattr(body, "cfg", None)
    if cfg is None or not ins or not any(it.cls == IS.TENSOR for it in ins):
        return None
    iv = shadow_inventory(ins, cfg)
    sub = substitution_audit(ins, iv["rows"])
    st = schedule_stats(ins)
    out("  1c. УКЛАДКА В ТЕНЬ: ОПИСЬ ОСТАТКА (кто не в тени и ПОЧЕМУ; карта не нужна)")
    per = period_of(ins)
    out(
        "     ПЕРИОД (max по каналам, тактов на ВАРП за итерацию) -- вот шаг, внутрь которого "
        "обязано уместиться ВСЁ остальное:"
    )
    out(
        "        %s"
        % ", ".join(
            "%s %.0f%s" % (k, v, "  <== ЗАДАЁТ ПЕРИОД" if k == per["binding"] else "")
            for k, v in per["rows"]
        )
    )
    if st:
        out(
            "     ПРЕВЫШЕНИЕ НАД ПЕРИОДОМ: расписание %.0f - период %.0f = %.0f тактов "
            "<== ЦЕЛЕВАЯ ФУНКЦИЯ. Доля в тени -- СЛЕДСТВИЕ и хороший диагноз, но оптимизировать "
            "надо превышение"
            % (st["sched"], per["period"], st["sched"] - per["period"])
        )
    out(
        "     МЕСТА: теней %d (по одной на тензорную команду) | занято %d | ПУСТУЕТ %d | "
        "предметов %d -- избыток мест %.1fx"
        % (
            iv["hmma"],
            iv["busy"],
            iv["free"],
            iv["non"],
            iv["hmma"] / float(max(iv["non"], 1)),
        )
    )
    out("     ВНЕ ТЕНИ %d команд, из них:" % len(iv["rows"]))
    for w, c in sorted(iv["by_why"].items(), key=lambda x: -x[1]):
        cls = collections.Counter(r["cls"] for r in iv["rows"] if r["why"] == w)
        out(
            "        %-16s %4d   %s"
            % (w, c, ", ".join("%s %d" % kv for kv in cls.most_common(5)))
        )
    out(
        "     ОСНОВНЫХ БЛОКОВ в мейнлупе %d, с тензорными командами %d "
        "(тени существуют ТОЛЬКО в них; через границу блока сборщик не переносит ничего)"
        % (iv["nblocks"], iv["nblocks_with_shadow"])
    )
    for a, h in sorted(iv["blocks"].items()):
        nn = sum(1 for r in iv["rows"] if r["blk"] == a)
        out(
            "        блок %#010x  тензорных %4d  вне тени %4d%s"
            % (a, h, nn, "   <== ТЕНЕЙ НЕТ ВОВСЕ" if h == 0 else "")
        )
    out(
        "     УКЛАДЧИК (списочное планирование по критическому пути; поля задержки НЕ ЧИТАЮТСЯ)"
    )
    out(
        "        на ЭТОМ исходнике:        расписание %7.1f | в тени %3d/%d | остаток %3d"
        % (iv["asis"]["sched"], iv["asis"]["in"], iv["non"], len(iv["asis"]["rest"]))
    )
    out(
        "        после ПЕРЕСТРОЙКИ:        расписание %7.1f | в тени %3d/%d | остаток %3d "
        "(один основной блок + непересекающиеся половины буфера)"
        % (
            iv["rebuilt"]["sched"],
            iv["rebuilt"]["in"],
            iv["non"],
            len(iv["rebuilt"]["rest"]),
        )
    )
    # ПОРОДА ТЕЛА -- УСЛОВИЕ ГОДНОСТИ ПРЕДЫДУЩЕЙ СТРОКИ (LAW=L-MERGE-NOT-FOR-INHERITED).
    _порода, _оговорка = body_breed(iv["hmma"], iv["hmma"] + iv["non"])
    out("        ПОРОДА ТЕЛА: %s -- %s" % (_порода, _оговорка))
    # ЗНАК НЕРАВЕНСТВА ПРОВЕРЯЕТСЯ ЗДЕСЬ ЖЕ, А НЕ ПОДРАЗУМЕВАЕТСЯ (LAW=L-FLOOR-MUST-NOT-EXCEED-FOUND).
    # На 18 отгруженных телах из 25 напечатанная «нижняя граница» ВЫШЕ расписания, которое находит
    # тот же укладчик, -- то есть это ВЕРХНЯЯ оценка под именем нижней.  Величина НЕ ПРАВЛЕНА
    # (наряд #154 -- опись, а не правка); правило обязано хотя бы НЕ ВРАТЬ про знак.
    _пол_укл = iv["rebuilt"]["floor"]
    _найдено = min(iv["asis"]["sched"], iv["rebuilt"]["sched"])
    out(
        "        нижняя граница укладки:   расписание %7.1f  (тензорный пол + по 1.00 на предмет)%s"
        % (
            _пол_укл,
            ""
            if _пол_укл <= _найдено + 1e-9
            else "  <== ЭТО НЕ ПОЛ: выше найденного расписания %.1f, читать как ВЕРХНЮЮ оценку"
            % _найдено,
        )
    )
    out(
        "        MaxLive укладки %d + %d = %d против бюджета %d -- %s"
        % (
            iv["rebuilt"]["maxlive"],
            T.REG_OVERHEAD,
            iv["rebuilt"]["maxlive"] + T.REG_OVERHEAD,
            iv["reg_budget"] + T.REG_OVERHEAD,
            "РЕГИСТРЫ НЕ СВЯЗЫВАЮТ УКЛАДКУ"
            if iv["regs_short"] == 0
            else "НЕ ВЛЕЗАЕТ: не хватает %d" % iv["regs_short"],
        )
    )
    out(
        "     ЗАМЕЩЕНИЕ КАНАЛА (нетензорное -> тензорное): курс -1.45 такта у предмета ВНЕ тени "
        "(в голове серии; до -2.90 в середине) и +2.00 у предмета, УЖЕ СТОЯЩЕГО В ТЕНИ"
    )
    out(
        "        счётных в остатке %d: над ЗАГРУЖЕННЫМИ ДАННЫМИ %d (тензорная форма есть), "
        "над АДРЕСОМ %d (тензорной формы нет); команд FPU во всём теле %d"
        % (sub["count"], sub["over_data"], sub["over_addr"], sub["fpu_body"])
    )
    if listing:
        out("     ПЕРЕЧЕНЬ ОСТАТКА (первые %d):" % listing)
        for r in iv["rows"][:listing]:
            out(
                "        %#08x %-16s %-13s d=%+5d  %s"
                % (r["addr"], r["why"], r["cls"], r["dist"], r["text"][:56])
            )
    out("")
    return iv


def report(body, chan, verdict, props, warps, host_hmma=None, out=print, listing=0):
    out("=" * 100)
    out("ТЕЛО %s" % body.label[:88])
    out("  что взято за итерацию: %s" % body.how)
    out(
        "  команд %d, варпов на SM %d (варпов на планировщик %.2f)"
        % (body.n, warps, warps / float(T.SCHEDULERS))
    )
    out("")
    out("  1. ЗАГРУЗКА ПО КАНАЛАМ (тактов на итерацию)")
    out("     %-8s %18s %8s  %s" % ("канал", "нагрузка", "доля", "чем задана ставка"))
    top = max([l.hi for l in chan.values() if not l.ref] or [1.0])
    for c, l in sorted(chan.items(), key=lambda kv: -kv[1].hi):
        mark = (
            "  <== СВЯЗЫВАЕТ"
            if (verdict.kind == "ресурс" and c == verdict.channel)
            else ("  (справочно)" if l.ref else "")
        )
        out(
            "     %-8s %18s %7.0f%%  %s%s"
            % (c, repr(l), 100.0 * l.hi / top, l.why, mark)
        )
    out(
        "     ResMII = %.1f тактов%s"
        % (
            verdict.resmii,
            ""
            if verdict.kind != "молчит"
            else "  (по верхней оценке спорящего канала)",
        )
    )
    out("")
    st_sched = schedule_block(body, out=out, listing=listing)
    out("  2. RecMII (длиннейший контур графа зависимостей с ЗАМЕРЕННЫМИ задержками)")
    if body.n > REC_LIMIT:
        out(
            "     НЕ ПОСЧИТАН: тело %d команд > %d. Это ОТКАЗ, а не ноль -- подставлять оценку "
            "вместо счёта запрещено. Считать выше порога: --rec-limit N (ЗАМЕРЕННАЯ цена "
            "%s)." % (body.n, REC_LIMIT, REC_COST_NOTE)
        )
    else:
        out(
            "     RecMII = %.1f тактов (%.0f %% от ResMII)%s"
            % (
                verdict.recmii,
                100.0 * verdict.recmii / max(verdict.resmii, 1e-9),
                "  -- ЗАМКНУТЫХ КОНТУРОВ НЕТ: цепочка прямолинейна, повторение ничем не удерживается"
                if verdict.recmii < 1e-6
                else "",
            )
        )
    out("")
    out("  3. ВЕРДИКТ")
    if verdict.kind == "ресурс":
        out(
            "     СВЯЗЫВАЕТ РЕСУРС: канал %s, %.1f тактов на итерацию."
            % (verdict.channel, verdict.resmii)
        )
    elif verdict.kind == "зависимости":
        out(
            "     СВЯЗЫВАЮТ ЗАВИСИМОСТИ: RecMII %.1f > ResMII %.1f."
            % (verdict.recmii, verdict.resmii)
        )
    else:
        out("     МОДЕЛЬ МОЛЧИТ. %s" % verdict.note)
        out("     Спорят: %s" % ", ".join(verdict.contenders))
        # МОЛЧАНИЕ О КАНАЛЕ -- НЕ МОЛЧАНИЕ О ТЕЛЕ.  Каналы действительно не расходятся; но на
        # этом самом классе тел расходится РАСПИСАНИЕ, и читатель обязан увидеть это здесь, а
        # не только в 1b: именно из-за отсутствия такой строки инструмент дал ОДИН вердикт на
        # телах с разницей времени в 1.20 раза.
        if st_sched and st_sched["hmma"]:
            out(
                "     НО ТЕЛА РАЗЛИЧАЕТ РАСПИСАНИЕ (R9, см. 1b): запас %.3f -> доля тензорной "
                "трубы %.1f %%, самая длинная нетензорная серия %d команд. Это ЧИТАЕТСЯ ИЗ "
                "МАШИННОГО КОДА, домерять нечего."
                % (st_sched["slack"], pipe_share(st_sched["slack"]), st_sched["run"])
            )
    if verdict.dram_threshold is not None:
        out(
            "     ПОРОГ ПО ПОЛОСЕ: DRAM перестаёт быть первым при попадании L2 выше %.1f %%."
            % verdict.dram_threshold
        )
    out("")
    out("  4. ПРЕДЛОЖЕНИЯ ИЗ МЕНЮ")
    for p in props:
        head = "СРАБОТАЛО" if p.fires else "не применимо"
        out("     [%s] %s" % (head, p.rule))
        for ln in _wrap(p.text, 92):
            out("         " + ln)
        if p.newbound is not None:
            out(
                "         ПРЕДСКАЗАННАЯ НОВАЯ ГРАНИЦА: %.1f тактов (было %.1f, %+.1f %%)"
                % (
                    p.newbound,
                    verdict.resmii,
                    100.0 * (p.newbound / max(verdict.resmii, 1e-9) - 1.0),
                )
            )
        if p.check:
            for ln in _wrap("чем проверять: " + p.check, 92):
                out("         " + ln)
    out("")
    out("  5. " + BOUND_LINE)
    out("=" * 100)


def _wrap(s, w):
    words, line, out = s.split(), "", []
    for x in words:
        if len(line) + len(x) + 1 > w:
            out.append(line)
            line = x
        else:
            line = (line + " " + x).strip()
    if line:
        out.append(line)
    return out


