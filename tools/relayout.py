def sched_time_invariant(bodies=None):
    """ПОПЫТКА ПЕРЕКАЛИБРОВКИ, доведённая до числа: что даёт ЕДИНАЯ константа на всех телах.

    Возвращает коридор инварианта (время x расписание), лучшую единую константу (среднее
    геометрическое -- оно не тянется за краем так, как среднее арифметическое) и МАКСИМАЛЬНУЮ
    ошибку предсказанного времени.  Ноль подгонки: константа считается по ВСЕМ телам сразу,
    а не подбирается под нулевую ошибку на выбранном.
    """
    bs = bodies if bodies is not None else SCHED_TIME_BODIES
    inv = [(b["имя"], b["время"] * b["расписание"], b) for b in bs]
    vals = [v for _, v, _ in inv]
    n = len(vals)
    prod = 1.0
    for v in vals:
        prod *= v
    k = prod ** (1.0 / n)
    err = [(nm, (k / b["расписание"]) / b["время"] - 1.0) for nm, v, b in inv]
    fit = [(nm, v, b) for nm, v, b in inv if not b["разлил"]]
    fv = [v for _, v, _ in fit]
    # СЕМЕЙСТВА.  Разброс инварианта -- НЕ шум: тела делятся по числу основных блоков мейнлупа,
    # и коридоры двух семейств НЕ ПЕРЕСЕКАЮТСЯ.  Значит «время x расписание» не одна константа,
    # а по константе на семейство, и предсказание величины ЧЕРЕЗ границу семейства обречено --
    # ровно так и вышло: KSTEPS=2 (один блок) предсказывали константой REF (пять блоков).
    fam = {}
    for nm, v, b in inv:
        fam.setdefault(b["блоков"], []).append(v)
    fams = sorted((n, min(vs), max(vs)) for n, vs in fam.items())
    gap = None
    if len(fams) == 2:
        lo, hi = sorted(fams, key=lambda f: f[2])
        gap = hi[1] / lo[2] - 1.0 if hi[1] > lo[2] else None
    return {
        "инвариант": inv,
        "коридор": (min(vals), max(vals)),
        "размах": max(vals) / min(vals) - 1.0,
        "коридор_влезающих": (min(fv), max(fv)),
        "размах_влезающих": max(fv) / min(fv) - 1.0,
        "константа": k,
        "ошибка": err,
        "макс_ошибка": max(abs(e) for _, e in err),
        "семейства": fams,
        "ступенька": gap,
    }


