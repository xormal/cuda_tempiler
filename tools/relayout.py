# ПОРОДА ТЕЛА ЧИТАЕТСЯ ДОЛЕЙ ТЕНЗОРНЫХ КОМАНД (LAW=L-MERGE-NOT-FOR-INHERITED).
# Сплошной прогон #154: наши рукописные тела держат 44-60 % тензорных команд, тела, унаследованные
# от чужой библиотеки внимания, -- 7-18 %; ядро ролей (23-31 %) стоит МЕЖДУ ними.  Замеренный
# потолок слияния основных блоков разделяется ровно по этой границе, а не по «качеству укладки».
BREED_INHERITED_MAX = (
    0.20  # доля тензорных, ниже которой тело читается как унаследованное
)
BREED_OURS_MIN = 0.40  # доля, выше которой тело читается как наше рукописное


def body_breed(hmma, n):
    """-> (порода, оговорка про слияние блоков).  Между порогами инструмент МОЛЧИТ."""
    share = hmma / float(max(n, 1))
    if share <= BREED_INHERITED_MAX:
        return (
            "УНАСЛЕДОВАННАЯ (%.0f %% тензорных)" % (100 * share),
            "СЛИЯНИЕ БЛОКОВ СЮДА НЕ ПЕРЕНОСИТСЯ: на всём семействе унаследованных тел замерено, "
            "что после перестройки укладчик даёт расписание ДЛИННЕЕ уже достигнутого сборщиком "
            "(+1.9..+8.1 %), тогда как на наших рукописных телах -- короче (до -30.7 %). Число "
            "рядом читать как РАНГ, а не как величину",
        )
    if share >= BREED_OURS_MIN:
        return (
            "НАША РУКОПИСНАЯ (%.0f %% тензорных)" % (100 * share),
            "на этой породе слияние блоков замеренно ДАЁТ (-15..-31 %), но число рядом -- РАНГ, "
            "а не величина: ошибка укладчика вне калибровки -14.9..+29.0 %",
        )
    return (
        "МЕЖДУ ПОРОДАМИ (%.0f %% тензорных)" % (100 * share),
        "порода не читается: 20-40 % тензорных -- полоса, где замера НЕТ ни на одной стороне, и "
        "переносить сюда вывод о слиянии блоков НЕЛЬЗЯ ни в ту, ни в другую сторону",
    )


