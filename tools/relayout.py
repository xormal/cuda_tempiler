# R10 УКЛАДКА В ТЕНЬ: ОПИСЬ ОСТАТКА (задача 135).  Только чтение машинного кода, карта не нужна.
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ R9, И ЗАЧЕМ НУЖНО ОБА.  R9 читает СУММУ поля задержки уже собранного
# тела и печатает агрегат: «в тени 25.9 % при достижимых 98.7 %».  Агрегат не отвечает на
# вопрос, который решает, что делать дальше: упёрлись мы в ЗАКОН или не доработал УКЛАДЧИК.
# Отвечает на него счёт мест: теней столько же, сколько тензорных команд (512), а предметов
# 162 -- ИЗБЫТОК ТРОЕКРАТНЫЙ.  Значит непоставленный предмет -- не нехватка места, и обязан
# быть назван ПОИМЁННО, с причиной и с расстоянием до ближайшей свободной тени.
#
# ЧЕТЫРЕ ПРИЧИНЫ, И ОНИ РАЗНЫЕ ПО ЛЕЧЕНИЮ:
#   БЛОК БЕЗ ТЕНЕЙ -- команда лежит в основном блоке, где НЕТ НИ ОДНОЙ тензорной команды.
#       Теней в её блоке нет вовсе, а через границу блока сборщик не переносит ничего.  Лечение
#       -- ИСХОДНИК (убрать ветвление из тела), и никакой перебор ключей сборщика тут не поможет.
#   ГОЛОВА ЦЕПИ -- команда в блоке с тенями, но всякая свободная тень стоит ПОЗЖЕ её
#       потребителя: внутри одной итерации её сдвинуть некуда.  Лечение -- поворот цепи через
#       обратную дугу (готовить данные шага k+1 во время шага k), то есть тоже ИСХОДНИК.
#   РЕГИСТРЫ -- тень достижима, но чтобы дотянуть до неё, надо продержать значения живыми
#       сверх бюджета.  Лечение -- живость, и цена названа числом (при каком бюджете достижимо).
#   УКЛАДКА -- тень достижима, регистров хватает, и она всё равно пуста.  Это недоработка
#       УКЛАДЧИКА, а не закон.
