class Prop(object):
    def __init__(self, rule, fires, text, newbound=None, check=""):
        self.rule, self.fires, self.text, self.newbound, self.check = (
            rule,
            fires,
            text,
            newbound,
            check,
        )


def _bound_without(chan, replace=None):
    """Граница, если заменить нагрузку одного/нескольких каналов (replace: {канал: новое})."""
    vals = []
    for c, l in chan.items():
        if l.ref:
            continue
        vals.append((replace or {}).get(c, l.hi))
    return max(vals) if vals else 0.0


def rule_R1_homogeneous(body, chan, warps):  # LAW=L-CHAIN-NOT-HOMOGENEOUS
    """ОДНОРОДНАЯ ЦЕПОЧКА: счётный канал 2.00 такта против выдачи 1.00.

    ALU и FPU -- РАЗНЫЕ каналы РАВНОЙ ёмкости, работающие одновременно, поэтому цепочка,
    сидящая на одном из них, идёт на 0.5 команды за такт при доступной 1.0.  Ровное разведение
    опускает границу вдвое БЕЗ сокращения счёта.  SFU в баланс не берётся: его ёмкость вчетверо
    меньше, перенос туда границу ПОДНИМЕТ.
    """
    wps = max(warps, 1) / float(T.SCHEDULERS)
    alu = chan.get(T.CH_ALU, Load(0, 0)).hi
    fpu = chan.get(T.CH_FPU, Load(0, 0)).hi
    issue = chan.get(T.CH_ISSUE, Load(0, 0)).hi
    if alu + fpu <= 0:
        return Prop(
            "R1 однородная цепочка", False, "счётных команд вне тензорной трубы нет"
        )
    top, topv = (T.CH_ALU, alu) if alu >= fpu else (T.CH_FPU, fpu)
    if topv <= issue * (1.0 + 1e-9):
        return Prop(
            "R1 однородная цепочка",
            False,
            "цепочка УЖЕ сбалансирована: старший счётный канал %s = %.0f не выше выдачи "
            "%.0f; пол переукладки -- ВЫДАЧА, дальше только СОКРАЩАТЬ команды"
            % (top, topv, issue),
        )
    balanced = (alu + fpu) / 2.0
    newbound = _bound_without(chan, {T.CH_ALU: balanced, T.CH_FPU: balanced})
    cur = _bound_without(chan)
    moved = (topv - balanced) / (
        2.0 * wps
    )  # команд: одна стоит 2.00 такта на планировщик
    return Prop(
        "R1 однородная цепочка",
        True,
        "канал %s несёт %.0f тактов при выдаче %.0f: цепочка идёт на %.2f команды за такт при "
        "доступной 1.00 (%.0f %% простоя второго счётного канала). Перенести ~%.0f команд на "
        "второй канал равной ёмкости (half2-арифметика HADD2/HFMA2 -- по FPU; сдвиги/маски/"
        "перестановки -- по ALU) БЕЗ сокращения счёта."
        % (
            top,
            topv,
            issue,
            (issue / topv) if topv else 0.0,
            100.0 * (1.0 - min(alu, fpu) / max(topv, 1e-9)),
            moved,
        ),
        newbound if newbound < cur else None,
        "A/B с ТОЖДЕСТВЕННЫМ ответом и медианой ОТНОШЕНИЙ; счёт команд НЕ менять -- иначе "
        "меряется не переукладка. Проверить регистры (R4): half2 держит два значения в одном "
        "регистре, но константы маршрута занимают свои",
    )


def rule_R2_sfu(body, chan):
    ins = body.all_ins()
    mufu = [it for it in ins if it.base == "MUFU"]
    conv = [it for it in ins if it.base in CONV_OPS]
    if not mufu and not conv:
        return Prop(
            "R2 дефицитный канал (SFU)", False, "команд SFU и конверсий в теле нет"
        )
    txt = []
    if mufu:
        txt.append(
            "MUFU: %d команд по ЗАМЕРЕННОЙ ставке 8.00 такта/команду/планировщик "
            "(вчетверо дороже ALU)" % len(mufu)
        )
    if conv:
        txt.append(
            "конверсии (%s): %d команд; %s"
            % (",".join(sorted({it.base for it in conv})), len(conv), SFU_NOTE)
        )
    sfu = chan.get(T.CH_SFU, Load(0, 0)).hi
    others = max(
        [l.hi for c, l in chan.items() if c != T.CH_SFU and not l.ref] or [0.0]
    )
    fires = sfu > others * (1.0 + BAND)
    if fires:
        newb = _bound_without(chan, {T.CH_SFU: 0.0})
        return Prop(
            "R2 дефицитный канал (SFU)",
            True,
            "; ".join(txt) + ". SFU СВЯЗЫВАЕТ (%.0f против %.0f у прочих): замена этих "
            "команд арифметикой на ALU/FPU сдвинет границу" % (sfu, others),
            newb,
            "перебрать замену на прямой битовый маршрут (volta_prims.h) и померить",
        )
    return Prop(
        "R2 дефицитный канал (SFU)",
        False,
        "; ".join(txt) + ". SFU НЕ связывает (%.0f против %.0f у прочих) -- замена не "
        "окупится: ЗАМЕРЕНО, что при плотности 0.14-0.56 маршруты с конверсиями и без "
        "них РАВНЫ (1.036/1.042 ... 1.159/1.165), и расходятся только на 0.844 "
        "(1.323 против 1.259)" % (sfu, others),
    )


def rule_R3_banks(
    body, chan, mio_wf=None, mio_nominal=None, lanemap=None, stride=None, pads=None
):
    if lanemap and stride:
        rows = BF.sweep(BF.rows_from_lanemap(lanemap), stride, pads or range(0, 16))
        base = rows[0][2]
        best = min(rows, key=lambda r: (r[2], r[0]))
        mio = chan.get(T.CH_MIO)
        newb = None
        if mio and base > 0:
            newb = _bound_without(chan, {T.CH_MIO: mio.hi * best[2] / base})
        return Prop(
            "R3 конфликтность банков",
            best[2] < base,
            "замкнутая форма |R|/|{r*S mod 32}| по карте полос %r: сейчас %.2f при шаге %d "
            "слов, минимум %.2f при дополнении %d слов (S=%d)"
            % (lanemap, base, stride, best[2], best[0], best[1]),
            newb,
            "одностороннее «дополнить» НЕВЕРНО: в замеренной кривой pad=4 и 12 ХУЖЕ базы. "
            "При равной конфликтности брать МЕНЬШЕЕ дополнение",
        )
    if mio_wf and mio_nominal and mio_wf > mio_nominal * 1.001:
        share = 1.0 - mio_nominal / mio_wf
        mio = chan[T.CH_MIO]
        newb = _bound_without(chan, {T.CH_MIO: mio.hi * mio_nominal / mio_wf})
        return Prop(
            "R3 конфликтность банков",
            True,
            "ЗАМЕР цены команды разделяемой памяти (%.3f) ВЫШЕ номинальной ставки (%.3f): "
            "%.1f %% трафика MIO добавлено БАНКОВЫМИ КОНФЛИКТАМИ и возвратимо раскладкой"
            % (mio_wf, mio_nominal, 100 * share),
            newb,
            "карту полос виновного массива подать ключами --lanemap/--stride: формула даст "
            "дополнение мгновенно и без сборки (tools/bankform.py)",
        )
    return Prop(
        "R3 конфликтность банков",
        False,
        "карта полос не задана (--lanemap/--stride), замера цены команды нет -- "
        "конфликтность ИЗ МАШИННОГО КОДА НЕ ВЫВОДИТСЯ, модель берёт её минимум (=1)",
    )


def maxlive(body, wide=True):
    """MaxLive тела -- своего закона не вводим, берём счётчик планировщика.

    ЕДИНИЦА -- ЯЧЕЙКА, А НЕ ИМЯ (задача 141, LAW=L-REG-WIDTH-NOT-NAMES).  Прежняя редакция
    считала имена и занижала ВДВОЕ: 117 против ptxas 250.  wide=False оставлено ровно затем,
    чтобы гейт мог показать, что прежняя редакция его ПРОВАЛИВАЕТ.
    """
    ins = body.all_ins()
    if not ins:
        return None
    return SCH.live_cyclic(ins, wide=wide)


def rule_R4_regs(body, chan, warps):
    """R4 РЕГИСТРОВОЕ ДАВЛЕНИЕ (LAW=L-REG-WIDTH-NOT-NAMES).

    R_треб = MaxLive(ПО ШИРИНЕ) + РАЗЛИТОЕ(из опкодов) + REG_OVERHEAD.  Про второе слагаемое
    и про то, почему оно не делает модель постфактумной, -- см. regs_need().
    """
    ins = body.all_ins()
    ml = maxlive(body)
    if ml is None:
        return Prop("R4 регистровое давление", False, "тело пусто")
    sp = IS.spill_words(ins)
    need = ml + sp + T.REG_OVERHEAD
    q = T.reg_budget(warps)
    fits = need <= q
    spill_txt = (
        ""
        if not sp
        else " ТЕЛО УЖЕ РАЗЛИЛО: %d слов лежит в локальной памяти, и на столько же ЗАНИЖЕНА "
        "прочитанная живость (разлитое значение в регистре не живёт) -- поэтому они "
        "прибавлены, а не вычтены." % sp
    )
    if fits:
        wmax = max([w for w in range(1, 33) if need <= T.reg_budget(w)] or [0])
        return Prop(
            "R4 регистровое давление",
            False,
            "MaxLive %d + разлив %d + %d = %d требуемых против бюджета Q(%d)=%d -- "
            "ВЛЕЗАЕТ (запас %d); при этой живости бюджета хватает вплоть до %d варпов.%s"
            % (ml, sp, T.REG_OVERHEAD, need, warps, q, q - need, wmax, spill_txt)
            + " "
            + REG_BUDGET_NOTE,
            None,
            "МОДЕЛЬ ЖИВОСТИ -- НИЖНЯЯ ОЦЕНКА: она читает мейнлуп, а сборщик распределяет "
            "регистры на ВСЁ ядро. «Влезает» тут значит «мейнлуп не мешает», а не "
            "«сборка не разольёт»; проверять ptxas (регистры / разлив / КАДР СТЕКА -- "
            "ТРИ РАЗНЫХ числа) и опкоды LDL/STL",
        )
    wok = max([w for w in range(1, 33) if need <= T.reg_budget(w)] or [0])
    return Prop(
        "R4 регистровое давление",
        True,
        "MaxLive %d + разлив %d + %d = %d требуемых против бюджета Q(%d)=%d -- РАЗЛИВ. "
        "Цена НЕ такт: одно разлитое значение 27-32 такта против 4 (x5.1 на шаге, x75.7 "
        "у края). Лечения два: снизить занятость до %d варпов (бюджет %d) либо сократить "
        "живость на %d значений.%s"
        % (
            ml,
            sp,
            T.REG_OVERHEAD,
            need,
            warps,
            q,
            wok,
            T.reg_budget(wok),
            need - q,
            spill_txt,
        ),
        None,
        "проверить ptxas НАПРЯМУЮ (tools/cc_ab.py): регистры / разлив / КАДР СТЕКА -- "
        "ТРИ РАЗНЫХ числа, и отчёт компилятора о разливе неполон",
    )


def rule_R6_streams(body, chan, matrix_bytes=None, contiguous=None):
    """R6 ПОТОКИ И ЧЕРЕССТРОЧНОСТЬ (LAW=L-STREAMS-FREE, LAW=L-INTERLACE-COST).

    ЗАМЕРЕНО, и это ДВА РАЗНЫХ закона, которые легко перепутать в один:
      * СПЛОШНЫЕ потоки БЕСПЛАТНЫ: при равном суммарном объёме 1/2/3 потока дали
        878.5 / 876.9 / 878.2 ГБ/с -- разброс 0.2 %, шум.  Значит хранить величину ДВУМЯ
        ПЛОСКОСТЯМИ (старшая часть отдельно, уточняющая отдельно) не стоит НИЧЕГО;
      * ЧЕРЕССТРОЧНОЕ чтение половины тензора теряет 25-29 % полосы ДАЖЕ кусками в четверть
        мегабайта: 32 Б -> 48 % полосы, 256 КиБ -> 75 %, сплошное -> 100 %.

    ОТСЮДА ПРАВИЛО, А НЕ ПОЖЕЛАНИЕ: решение «брать ли вторую плоскость» принимается ПО
    МАТРИЦЕ ЦЕЛИКОМ, а не по плитке.  Плиточный добор -- это и есть чересстрочность, и он
    съедает четверть полосы.  Тот же капкан уже стоил нам выигрыша на рассеянной записи
    (16 секторов на запрос вместо 4).
    """
    if "DRAM" not in chan or chan["DRAM"].ref:
        return Prop(
            "R6 потоки и чересстрочность",
            False,
            "внекристальной подачи в теле нет -- правило не о чем",
        )
    if contiguous is False:
        return Prop(
            "R6 потоки и чересстрочность",
            True,
            "доступ объявлен ЧЕРЕССТРОЧНЫМ: замерено 25-29 %% потери полосы даже кусками в "
            "256 КиБ (32 Б -> 48 %%, 64 Б -> 71 %%, 256 КиБ -> 75 %%, сплошное -> 100 %%). "
            "Лечение -- НЕ мельчить куски, а перейти на РАЗДЕЛЬНЫЕ СПЛОШНЫЕ потоки: их цена "
            "замерена в +1.1 %% (3.072 против 3.106 мс на паре 4:1), то есть практически ноль",
            None,
            "мерить полосу ДВУХ раскладок на одном объёме; признак ложного применения -- "
            "доступ ВНУТРИ потока остался разреженным, тогда это не про число потоков",
        )
    return Prop(
        "R6 потоки и чересстрочность",
        True,
        "доступ СПЛОШНОЙ: число потоков не платит (1/2/3 потока -> 878.5/876.9/878.2 ГБ/с, "
        "разброс 0.2 %% = шум). Значит расщепление величины на ДВЕ ПЛОСКОСТИ бесплатно по "
        "транспорту, и выбор разрядности можно менять НА ЛЕТУ, не переупаковывая. ОГРАНИЧЕНИЕ "
        "ОБЛАСТИ: решение принимается ПО МАТРИЦЕ ЦЕЛИКОМ -- плиточный добор превращает поток в "
        "чересстрочный и стоит 25-29 %% полосы",
        None,
        "замер снят ЧИСТЫМ чтением без ядра: в настоящем теле есть предвыборка, кэш второго "
        "уровня и очередь, и отклонение может оказаться и мягче, и жёстче",
    )


def rule_R7_amortize_m(body, chan, mb=None, host_hmma=None, warps=None):
    """R7 АМОРТИЗАЦИЯ РАСПАКОВКИ ПО ПЛИТКЕ M (LAW=L-UNPACK-AMORT-1M).

    Вес разворачивается ОДИН раз и переиспользуется всеми M строками активации, поэтому
    накладные распаковки падают как 1/M.  Замеренные +16.5 % сняты при MB=4; удвоение плитки
    по M режет их примерно вдвое БЕЗ ЕДИНОГО ИЗМЕНЕНИЯ В ЦЕПОЧКЕ.

    ПОЧЕМУ ЭТО ПРАВИЛО, А НЕ ЗАМЕЧАНИЕ.  Это САМЫЙ ДЕШЁВЫЙ живой рычаг узкого формата: он не
    требует ни новой математики, ни новых команд.  Два других (балансировка каналов R1 и
    свёртка констант R8) либо мертвы на этом теле, либо требуют работы математика.
    """
    if not mb:
        return Prop(
            "R7 амортизация по M",
            False,
            "плитка по M не задана (ключ --mb): правило зависит от ФОРМЫ ПЛИТКИ, а не "
            "от тела, и без неё оно молчит",
        )
    n = body.n
    if n <= 0 or not host_hmma:
        return Prop(
            "R7 амортизация по M",
            False,
            "нет ни цепочки, ни хозяина -- амортизировать нечего",
        )
    dens = n / float(host_hmma)
    lo = SLOT_PRICE[0] * n * (warps or body.warps)
    return Prop(
        "R7 амортизация по M",
        True,
        "цепочка %d команд при плитке MB=%d: плотность %.3f команды распаковки на тензорную. "
        "Вес разворачивается ОДИН раз на %d строк, поэтому удвоение MB до %d режет накладные "
        "ПРИМЕРНО ВДВОЕ (замер: +16.5 %% при MB=4 -> около +8 %% при MB=8), не трогая ни одной "
        "команды цепочки. Это дешевле балансировки каналов и дешевле свёртки констант -- "
        "ПРОВЕРЯТЬ ПЕРВЫМ" % (n, mb, dens, mb * 16, mb * 2),
        None,
        "ГЕЙТ НА ОДНУ ВОЛНУ ВО ВСЕХ ПЛЕЧАХ ОБЯЗАТЕЛЕН: удвоение M меняет живость и может "
        "сменить число блоков на процессоре, и тогда замерится КВАНТОВАНИЕ ВОЛН, а не "
        "амортизация -- на этом уже потеряли +34 % на ровном месте (67 регистров против 64 "
        "дали 3 блока вместо 4)",
    )


def rule_R8_fold_constants(body, chan, bits=None):
    """R8 СВЁРТКА КОНСТАНТ И НИЖНЯЯ ГРАНИЦА РАСПАКОВКИ (LAW=L-FOLD-RANK1, LAW=L-PLANE-J-AND-JG2).

    ДОКАЗАНО (не замерено -- доказано, и потому фальсификатор КОНСТРУКТИВНЫЙ):
      * всё постоянное на группе смещения уходит ОДНОЙ поправкой ранга один; групповой масштаб,
        знаковое расширение и множитель степени двойки стоят НОЛЬ действий на индекс;
      * БАЙТОВАЯ плоскость строится ДВУМЯ ПЕРЕСТАНОВКАМИ БЕЗ АРИФМЕТИКИ -- 1/2 действия на индекс;
      * НИБЛОВУЮ перестановкой построить НЕЛЬЗЯ: байт неделим и содержит ниблы ДВУХ соседних
        индексов, перекрёстный вклад не чинится никакой поправкой;
      * НИЖНЯЯ ГРАНИЦА: при 12 битах любая ТОЧНАЯ схема тратит вне тензорной операции
        >= 1 словного действия на индекс; при 16 битах -- 0.

    ЧТО ЭТО ЗНАЧИТ ОПЕРАЦИОННО.  Мы меняем 25 % байт на >= 1 словное действие на индекс, и это
    действие замерено в 0.15 такта.  Что дороже -- решает ФАЗА, а не вкус: в памятно связанной
    выигрывают байты, в счётно связанной -- проигрывают.  Схема на 2.25 действия имеет запас до
    1-1.5; ниже 1.0 идти НЕКУДА, и это дно, а не плохая реализация.

    И ОТДЕЛЬНО -- РАСКЛАДКА: байт j нибловой плоскости обязан нести ниблы элементов j и j+G/2,
    а не j и j+1. Перестановка индексов, не меняющая ответ НИ НА БИТ, меняет цену на +44 %.
    """
    n = body.n
    if n <= 0:
        return Prop("R8 свёртка констант", False, "тело пусто")
    if bits is None:
        return Prop(
            "R8 свёртка констант",
            False,
            "разрядность кода не задана (ключ --bits): нижняя граница -- ФУНКЦИЯ "
            "РАЗРЯДНОСТИ (12 бит -> >=1 действие на индекс, 16 бит -> 0), и без неё "
            "правило назначило бы границу вместо того, чтобы её знать",
        )
    floor = 0.0 if bits >= 16 else 1.0
    return Prop(
        "R8 свёртка констант",
        True,
        "при %d битах нижняя граница вне тензорной операции = %.1f словного действия на индекс "
        "(ДОКАЗАНА, не оценена). Что снимается бесплатно: групповой масштаб -> 0, знаковое "
        "расширение -> 0 (перекодировка ПРИ УПАКОВКЕ), множитель степени двойки -> 0 (в "
        "групповую константу), ВСЕ постоянные смещения -> ОДНА поправка ранга один на группу. "
        "Байтовая плоскость -- ДВЕ ПЕРЕСТАНОВКИ без арифметики (1/2 действия); нибловая "
        "перестановкой НЕВОЗМОЖНА (байт неделим и несёт ниблы ДВУХ индексов). Раскладка: байт j "
        "обязан нести j и j+G/2, а не j и j+1 -- иначе +44 %% команд при том же ответе"
        % (bits, floor),
        None,
        "фальсификатор КОНСТРУКТИВНЫЙ: предъявить точную схему в МЕНЬШЕ чем %.1f действия на "
        "индекс. Секундомер здесь ничего не решает. ОГОВОРКА: со свёрнутыми смещениями "
        "слагаемые раздуты и требуют НЕОКРУГЛЁННЫХ групповых частичных сумм; не хватит окна "
        "накопителя -- вычитать по элементам (+1/2 действия)" % floor,
    )


