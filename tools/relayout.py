# 2. КАНАЛЫ: интервал [нижняя ставка, номинальная] по каждому
#
# ПОЧЕМУ ИНТЕРВАЛ, А НЕ ЧИСЛО.  Единственная ставка, которую модель НЕ ЗНАЕТ из машинного кода, --
# конфликтность раскладки.  Нижняя (конфликтность = 1) ЗАКОННА как граница: 0 нарушений на 643
# точках стенда.  Номинальная ("все полосы различны") точнее там, где адреса различны, но границей
# НЕ является: 51 нарушение из 643.  Печатать одно число вместо интервала -- значит выдать
# незнание за точность.
# ------------------------------------------------------------------------------------------------
class Load(object):
    def __init__(self, lo, hi, why="", ref=False, full=None):
        self.lo, self.hi, self.why, self.ref = float(lo), float(hi), why, ref
        self.full = (
            full  # для DRAM: нагрузка при НУЛЕ попаданий (нужна для порога по полосе)
        )

    def one(self):
        return abs(self.hi - self.lo) < 1e-9

    def __repr__(self):
        return "%.1f" % self.hi if self.one() else "%.1f..%.1f" % (self.lo, self.hi)


def _pipe_loads(parts, safe):
    load = collections.Counter()
    for _, ins, w in parts:
        for it in ins:
            for ch, c in T.footprint(it, safe=safe).items():
                load[ch] += c * w
    return load


def gmem_bytes(parts):
    """Байт глобальной памяти НА SM за итерацию, при допущении РАЗЛИЧНЫХ адресов у 32 полос.

    Это ОЦЕНКА СВЕРХУ трафика: рассылка одного адреса дала бы меньше.  Для полосного канала
    оценка сверху -- законная сторона: она может ложно ОБВИНИТЬ полосу, но не может её
    оправдать, поэтому вывод "полоса НЕ связывает" из неё СТРОГИЙ, а обратный -- условный.
    """
    tot = 0.0
    for _, ins, w in parts:
        tot += sum(IS.width_of(it) for it in ins if it.cls in MEM_CLS) * 32 * w
    return tot


def channel_table(body, mio_wf=None, mio_nominal=None, l2_hit=None):
    """-> {канал: Load}.  Все величины -- ТАКТЫ на итерацию при данной занятости."""
    safe = _pipe_loads(body.parts, True)
    nom = _pipe_loads(body.parts, False)
    out = {}
    for ch in set(safe) | set(nom):
        if ch == T.CH_MIO:
            lo, hi = safe[ch] / T.MIO_BYTES_PER_CYCLE, nom[ch] / T.MIO_BYTES_PER_CYCLE
            why = "нижняя = конфликтность 1 (ГРАНИЦА, 0 нарушений на 643 точках); верхняя = все полосы различны"
            if mio_wf and mio_nominal:
                # ЗАМЕР цены команды разделяемой памяти (ncu) -- интервал схлопывается.
                k = mio_wf / mio_nominal
                lo = hi = hi * k
                why = (
                    "ЗАМЕР ncu: %.3f вайвфронта на команду против номинальных %.3f (x%.3f)"
                    % (mio_wf, mio_nominal, k)
                )
            out[ch] = Load(lo, hi, why)
        else:
            v = safe[ch] / float(T.SCHEDULERS)
            out[ch] = Load(
                v,
                v,
                "ёмкость %s такта/команду/планировщик"
                % (
                    {
                        T.CH_TENSOR: "2.00",
                        T.CH_ALU: "2.00",
                        T.CH_FPU: "2.00",
                        T.CH_SFU: "8.00",
                        T.CH_ISSUE: "1.00",
                        T.CH_BRANCH: "1.00",
                        T.CH_LSU: "1.00",
                    }.get(ch, "?")
                ),
            )
    gb = gmem_bytes(body.parts)
    if gb:
        full = gb / HBM_B_PER_CYCLE_SM
        if l2_hit is None:
            out["DRAM"] = Load(
                0.0,
                full,
                "попадания L2 НЕ ЗАДАНЫ: нижняя = все попали, верхняя = все промахнулись",
                full=full,
            )
        else:
            v = full * (1.0 - l2_hit / 100.0)
            out["DRAM"] = Load(
                v, v, "попаданий L2 %.2f %% (ЗАМЕР, задан ключом)" % l2_hit, full=full
            )
        out["L2"] = Load(
            gb / L2_B_PER_CYCLE_SM,
            gb / L2_B_PER_CYCLE_SM,
            "ёмкость 2155 ГБ/с -- ОЦЕНКА СВЕРХУ, НЕ ЗАМЕР: в выборах не участвует",
            ref=True,
        )
    return out


