def compiler_regs(path, kernel_pat):
    """Что О ТОМ ЖЕ ТЕЛЕ говорит КОМПИЛЯТОР: регистры / кадр стека / локальная память.

    ЭТО ФАЛЬСИФИКАТОР ПРАВИЛА R4, а не украшение: модель считает MaxLive по машинному коду и
    прибавляет замеренные 7, а ptxas объявляет своё число в том же файле.  Расхождение видно
    БЕЗ КАРТЫ и БЕЗ СБОРКИ.  Три числа РАЗНЫЕ (регистры / разлив / КАДР СТЕКА) -- поэтому
    печатаются все три: отчёт компилятора о разливе неполон, признак -- LOCAL/STACK.
    """
    try:
        out = IS.subprocess.run(
            [IS.find_cuobjdump(), "-res-usage", path], capture_output=True, text=True
        ).stdout
    except Exception:
        return None
    cur = None
    for line in out.split("\n"):
        m = re.search(r"Function (\S+):", line)
        if m:
            cur = m.group(1)
            continue
        m = re.search(r"REG:(\d+)\s+STACK:(\d+)\s+SHARED:(\d+)\s+LOCAL:(\d+)", line)
        if m and cur and re.search(kernel_pat, cur):
            return {
                "reg": int(m.group(1)),
                "stack": int(m.group(2)),
                "shared": int(m.group(3)),
                "local": int(m.group(4)),
                "kernel": cur,
            }
    return None


class _A(object):
    """Набор ключей разбора -- то же, что даёт argparse, но собираемое кодом."""

    def __init__(self, **kw):
        self.obj = None
        self.kernel = None
        self.sass = False
        self.warps = None
        self.roles = False
        self.core = False
        self.whole = False
        self.strip_io = False
        self.calib = False
        self.l2_hit = None
        self.host_hmma = None
        self.lanemap = None
        self.stride = None
        self.pad = None
        self.json = None
        self.mb = None
        self.bits = None
        self.interlaced = False
        self.rec_limit = None
        self.inventory = 0
        for k, v in kw.items():
            setattr(self, k, v)


def gate(out=print, verbose=True):
    out("=" * 100)
    out("ГЕЙТ ГОДНОСТИ: три тела, у каждого связывающий ресурс УЖЕ ЗАМЕРЕН")
    out("=" * 100)
    rows = []
    for g in GATE:
        out("")
        out("### %s" % g["имя"])
        out("    ЗАМЕР: %s" % g["замер"])
        if not os.path.exists(g["путь"]):
            out("    ПРОПУЩЕН: нет %s" % g["путь"])
            rows.append((g["имя"], g["ждём"], "нет тела", "ПРОПУЩЕН"))
            continue
        if g.get("почему l2"):
            out("    ВХОД МОДЕЛИ: %s" % g["почему l2"])
        kw = dict(g["ключи"])
        if kw.get("warps") is None:
            kw.pop("warps", None)
        a = _A(obj=g["путь"], kernel=g["образец"], sass=g.get("sass", False), **kw)
        res = analyse(a, out=(out if verbose else (lambda *_: None)))
        v = res["verdict"]
        got = (
            v.channel
            if v.kind == "ресурс"
            else (res["phase"]["binding"] if res["phase"] else "МОЛЧИТ")
        )
        good = got == g["ждём"]
        if not g.get("sass"):
            cr = compiler_regs(g["путь"], g["образец"])
            if cr:
                rn = regs_need(res["body"].all_ins())
                out(
                    "    СВЕРКА R4 С КОМПИЛЯТОРОМ (ptxas, без карты и без сборки): REG=%d "
                    "STACK=%d LOCAL=%d; модель MaxLive %d + разлив %d + %d = %d (%+d регистра), "
                    "вердикт %s. %s"
                    % (
                        cr["reg"],
                        cr["stack"],
                        cr["local"],
                        rn["maxlive"],
                        rn["spill"],
                        T.REG_OVERHEAD,
                        rn["need"],
                        rn["need"] - cr["reg"],
                        rn["verdict"],
                        "LOCAL=0 и модель говорит ВЛЕЗАЕТ -- согласие"
                        if (cr["local"] == 0) == (rn["verdict"] == "влезает")
                        else "РАСХОЖДЕНИЕ С КОМПИЛЯТОРОМ, читать глазами",
                    )
                )
        out(
            "    ВЕРДИКТ v1: %s     ЖДАЛИ: %s     -> %s"
            % (got, g["ждём"], "СОВПАЛ" if good else "РАЗОШЁЛСЯ")
        )
        rows.append((g["имя"], g["ждём"], got, "ПРОЙДЕН" if good else "ПРОВАЛЕН"))
    out("")
    out("=" * 100)
    out("%-52s %-8s %-8s %s" % ("тело", "замер", "модель", "итог"))
    for n, e, got, st in rows:
        out("%-52s %-8s %-8s %s" % (n[:52], e, got, st))
    bad = [r for r in rows if r[3] == "ПРОВАЛЕН"]
    skipped = [r for r in rows if r[3] == "ПРОПУЩЕН"]
    out(
        "ИТОГ ГЕЙТА: %d из %d, пропущено %d"
        % (len(rows) - len(bad) - len(skipped), len(rows), len(skipped))
    )
    out(BOUND_LINE)
    return 1 if bad else 0


