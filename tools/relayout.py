def _rank_pairs(bs):
    """-> (верно, молчит, неверно) по всем парам: расписание против замеренного времени."""
    ok, silent, bad = [], [], []
    for i in range(len(bs)):
        for j in range(i + 1, len(bs)):
            a, b = bs[i], bs[j]
            d = abs(a["расписание"] - b["расписание"]) / float(
                max(a["расписание"], b["расписание"])
            )
            item = (
                "%s / %s (расписания %d против %d, %.1f %%; время %.4f против %.4f)"
                % (
                    _tag(a["имя"]),
                    _tag(b["имя"]),
                    a["расписание"],
                    b["расписание"],
                    100 * d,
                    a["время"],
                    b["время"],
                )
            )
            if abs(a["время"] - b["время"]) < TIME_RES:
                continue
            if d <= SCHED_BAND:
                silent.append(item)
            elif (a["расписание"] < b["расписание"]) == (a["время"] > b["время"]):
                ok.append(item)
            else:
                bad.append(item)
    return ok, silent, bad


