def pipe_share(slack, k=PIPE_K):
    return 100.0 * k * slack


def sched_part(body):
    """Роль, по которой читается расписание: та, где тензорных команд больше всего.

    Складывать расписания РОЛЕЙ нельзя: поле задержки предписано ВАРПУ, а роли -- это разные
    варпы, идущие ОДНОВРЕМЕННО.  Сумма по ролям была бы величиной, которой никто не ждёт.
    """
    best = None
    for name, ins, _w in body.parts:
        nh = sum(1 for it in ins if it.cls == IS.TENSOR)
        if best is None or nh > best[0]:
            best = (nh, name, ins)
    return (best[1], best[2]) if best else (None, [])


