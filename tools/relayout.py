class Verdict(object):
    def __init__(
        self, kind, channel, resmii, recmii, contenders, note, dram_threshold=None
    ):
        self.kind = kind  # "ресурс" | "зависимости" | "молчит"
        self.channel = channel
        self.resmii = resmii
        self.recmii = recmii
        self.contenders = contenders
        self.note = note
        self.dram_threshold = dram_threshold


def decide(chan, recmii, n_ins, rec_limit=None):
    """СТРОГОЕ ДОМИНИРОВАНИЕ или молчание.

    Назвать канал разрешено, только если его НИЖНЯЯ оценка выше ВЕРХНЕЙ оценки любого другого
    более чем на BAND (разрешающую способность модели).  Иначе -- "МОДЕЛЬ МОЛЧИТ" и список того,
    что надо домерить, чтобы спор разрешился.  Это правило R5: НАЗВАТЬ, А НЕ НАЗНАЧИТЬ.
    """
    play = {c: l for c, l in chan.items() if not l.ref}
    if not play:
        return Verdict("молчит", None, 0.0, recmii, [], "каналов нет")
    order = sorted(play.items(), key=lambda kv: -kv[1].hi)
    top, topl = order[0]
    resmii = topl.hi
    # ПОРОГ ПО ПОЛОСЕ (LAW=L-BW-VERDICT-ONE-WAY). Считается ВСЕГДА от трафика при НУЛЕ
    # попаданий -- это одностороннее и
    # потому сильное утверждение: попадания могут только УМЕНЬШИТЬ трафик, значит "полоса не
    # связывает" при пороге ниже замеренного попадания -- вывод СТРОГИЙ, а не условный.
    thr = None
    if "DRAM" in play and (play["DRAM"].full or 0) > 0:
        onchip = max([l.hi for c, l in play.items() if c != "DRAM"] or [0.0])
        full = play["DRAM"].full
        thr = 100.0 * (1.0 - onchip / full) if full > onchip else None
    rest = [(c, l) for c, l in order[1:]]
    if rest and topl.lo <= rest[0][1].hi * (1.0 + BAND):
        cont = [top] + [c for c, l in rest if _overlap(topl, l)]
        return Verdict(
            "молчит",
            None,
            resmii,
            recmii,
            cont,
            "разрыв между %s и %s меньше разрешающей способности модели (%.0f %%) "
            "или интервалы пересекаются" % (top, rest[0][0], 100 * BAND),
            thr,
        )
    if recmii > resmii * (1.0 + BAND) and n_ins <= (rec_limit or REC_LIMIT):
        return Verdict(
            "зависимости",
            None,
            resmii,
            recmii,
            [top],
            "RecMII превышает ResMII: связывает ДЛИНА КОНТУРА, а не ёмкость",
            thr,
        )
    return Verdict("ресурс", top, resmii, recmii, [top], "", thr)


def _overlap(a, b):
    return not (a.lo > b.hi * (1.0 + BAND))


