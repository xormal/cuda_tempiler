# 5. РЕЖИМ ФАЗЫ: цепочка, ВСТАВЛЕННАЯ в чужой цикл
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ РЕЖИМ.  Вопрос "что связывает ЦЕПОЧКУ" и вопрос "что стоит ДОБАВЛЕНИЕ цепочки в
# чужой цикл" -- РАЗНЫЕ, и второй -- тот, который задаёт заказчик.  Замер (EV_int12_prim.md §4)
# поставлен именно фазой: в тензорный цикл добавляется распаковка, читается ВРЕМЯ.
# ------------------------------------------------------------------------------------------------
def phase_report(body, chan, warps, host_hmma, out=print):
    wps = warps / float(T.SCHEDULERS)
    host = {T.CH_TENSOR: host_hmma * 2.0 * wps, T.CH_ISSUE: host_hmma * 1.0 * wps}
    host_top = max(host, key=host.get)
    host_bound = host[host_top]
    joint = dict(
        host
    )  # каналы хозяина обязаны быть в таблице целиком, иначе "пересечение"
    for c, l in chan.items():  # считалось бы против отсутствующего тензорного канала
        if l.ref:
            continue
        joint[c] = l.hi + host.get(c, 0.0)
    top = max(joint, key=joint.get)
    crossed = joint[top] > host_bound * (1.0 + 1e-9)
    n_per_warp = body.n
    n_per_sm = n_per_warp * warps
    lo = SLOT_PRICE[0] * n_per_sm
    hi = SLOT_PRICE[1] * n_per_sm
    out("")
    out(
        "  РЕЖИМ ФАЗЫ: цепочка вставлена в цикл с %d тензорными командами на варп, %d варпов/SM"
        % (host_hmma, warps)
    )
    out(
        "    цикл-хозяин без фазы:   %s = %.0f тактов (граница)"
        % (host_top, host_bound)
    )
    out("    он же с фазой:          %s = %.0f тактов" % (top, joint[top]))
    for c in sorted(joint, key=lambda x: -joint[x]):
        out("        %-8s %8.0f" % (c, joint[c]))
    cross = (joint[top] - host_bound) if crossed else 0.0
    if crossed:
        out(
            "    КАНАЛ %s ПЕРЕСЁК границу хозяина: прибавка ПО ЁМКОСТИ +%.0f тактов (%+.1f %%)"
            % (top, cross, 100.0 * cross / host_bound)
        )
    else:
        out(
            "    НИ ОДИН канал не пересёк границу хозяина -- по ёмкости фаза БЕСПЛАТНА."
        )
        out(
            "    Но «свободного конвейера НЕ СУЩЕСТВУЕТ» (ЗАМЕР): цена фазы -- СЛОТЫ ВЫДАЧИ."
        )
    out(
        "    ЦЕНА ПО ЗАМЕРЕННОЙ СТАВКЕ СЛОТА: %d команд на варп x %d варпов = %d команд/SM, "
        "по %.3f-%.3f такта = %.0f-%.0f тактов"
        % (n_per_warp, warps, n_per_sm, SLOT_PRICE[0], SLOT_PRICE[1], lo, hi)
    )
    # СЛОЖЕНИЕ ЗАПРЕЩЕНО: занятость порта выдачи УЖЕ учтена ставкой слота, поэтому прибавка по
    # ёмкости и цена слотов -- две оценки ОДНОГО И ТОГО ЖЕ, и берётся МАКСИМУМ.  Сложение давало
    # на маршруте конверсий +43.9 % против замеренных +32.3 % (проверено, отвергнуто).
    add_lo, add_hi = max(cross, lo), max(cross, hi)
    out(
        "    ИТОГО предсказание фазы (максимум из двух оценок, НЕ сумма): +%.1f..%.1f %% "
        "к периоду хозяина" % (100.0 * add_lo / host_bound, 100.0 * add_hi / host_bound)
    )
    binding = top if cross > hi else T.CH_ISSUE
    out(
        "    ВЕРДИКТ ФАЗЫ: %s"
        % (
            "связывает канал " + top
            if binding != T.CH_ISSUE
            else "ни один канал ёмкостью не связывает -- связывает ВЫДАЧА "
            "(цена линейна по числу команд, ЗАМЕР)"
        )
    )
    return {
        "host_bound": host_bound,
        "joint": joint,
        "crossed": crossed,
        "pred_lo": 100.0 * add_lo / host_bound,
        "pred_hi": 100.0 * add_hi / host_bound,
        "binding": binding,
    }


