#   Б. ВЕЛИЧИНА НЕ РАБОТАЕТ, и это показано ЧИСЛОМ, а не оговоркой: единая константа оставляет
#      ошибку времени БОЛЬШЕ, чем сами разницы, которые ранжируются.
#   В. ОБЛАСТЬ: тела С РАЗЛИВОМ ранг ПЕРЕВОРАЧИВАЮТ, и гейт обязан это показать -- иначе
