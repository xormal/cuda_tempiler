struct Variant {
  const char *name;
  int nh, ni, nc, np, ns, sw, nf, dup, strb;
  void (*fn)(uint64_t *, float *, int, const uint32_t *);
};

#define X(nm, NH, NI, NC, NP, NS, SW, NF) \
  {nm, NH, NI, NC, NP, NS, SW, NF, 1, (SW / 8), probe_kernel<NH, NI, NC, NP, NS, SW, NF, 1>},
#define XD(nm, NH, NI, NC, NP, NS, SW, NF, DUP) \
  {nm, NH, NI, NC, NP, NS, SW, NF, DUP, (SW / 8), probe_kernel<NH, NI, NC, NP, NS, SW, NF, DUP>},
#define XS(nm, NH, NI, NC, NP, NS, SW, NF, DUP, STRB) \
  {nm, NH, NI, NC, NP, NS, SW, NF, DUP, STRB, probe_kernel<NH, NI, NC, NP, NS, SW, NF, DUP, STRB>},
static Variant g_variants[] = {VARIANTS VARIANTS_D VARIANTS_S};
#undef X
#undef XD
#undef XS
static const int g_nvar = (int)(sizeof(g_variants) / sizeof(g_variants[0]));

int main(int argc, char **argv) {
  int warps = 8, iters = 2000, reps = 5, blocks = 80, exact = 0;
  const char *only = NULL;
  for (int i = 1; i < argc; ++i) {
    if (!strcmp(argv[i], "--warps") && i + 1 < argc) warps = atoi(argv[++i]);
    else if (!strcmp(argv[i], "--iters") && i + 1 < argc) iters = atoi(argv[++i]);
    else if (!strcmp(argv[i], "--reps") && i + 1 < argc) reps = atoi(argv[++i]);
    else if (!strcmp(argv[i], "--blocks") && i + 1 < argc) blocks = atoi(argv[++i]);
    else if (!strcmp(argv[i], "--only") && i + 1 < argc) only = argv[++i];
    else if (!strcmp(argv[i], "--exact")) exact = 1;
  }
  const int threads = warps * 32;
  const size_t smemBytes = 64 * 1024;   // >48 КБ => РОВНО один блок на SM

  uint64_t *dcyc; float *dsink; uint32_t *dz;
  CHECK(cudaMalloc(&dcyc, sizeof(uint64_t) * 2 * blocks * warps));
  CHECK(cudaMalloc(&dsink, sizeof(float) * blocks * threads));
  CHECK(cudaMalloc(&dz, sizeof(uint32_t) * 4));
  uint32_t hz[4] = {0u, 12345u, 0u, 0u};
  CHECK(cudaMemcpy(dz, hz, sizeof(hz), cudaMemcpyHostToDevice));

  printf("# warps=%d (на планировщик %.2f)  iters=%d  blocks=%d  reps=%d\n",
         warps, warps / 4.0, iters, blocks, reps);
  printf("%-18s %4s %4s %4s %4s %4s %4s %4s %4s %5s | %10s %10s\n",
         "вариант", "NH", "NI", "NC", "NP", "NS", "SW", "NF", "DUP", "STRB", "тактов/ит", "мин");

  for (int v = 0; v < g_nvar; ++v) {
    const Variant &V = g_variants[v];
    if (only && (exact ? strcmp(V.name, only) : !strstr(V.name, only))) continue;
    CHECK(cudaFuncSetAttribute(V.fn, cudaFuncAttributeMaxDynamicSharedMemorySize, (int)smemBytes));
    std::vector<double> med;
    for (int r = 0; r < reps; ++r) {
      V.fn<<<blocks, threads, smemBytes>>>(dcyc, dsink, iters, dz);
      CHECK(cudaGetLastError());
      CHECK(cudaDeviceSynchronize());
      std::vector<uint64_t> h(2 * blocks * warps);
      CHECK(cudaMemcpy(h.data(), dcyc, sizeof(uint64_t) * h.size(), cudaMemcpyDeviceToHost));
      std::vector<double> per;
      for (int b = 0; b < blocks; ++b) {
        uint64_t lo = ~0ull, hi = 0;
        for (int w = 0; w < warps; ++w) {
          lo = std::min(lo, h[2 * (b * warps + w)]);
          hi = std::max(hi, h[2 * (b * warps + w) + 1]);
        }
        per.push_back((double)(hi - lo) / iters);
      }
      std::sort(per.begin(), per.end());
      med.push_back(per[per.size() / 2]);
    }
    std::sort(med.begin(), med.end());
    const double t = med[med.size() / 2];
    printf("%-18s %4d %4d %4d %4d %4d %4d %4d %4d %5d | %10.4f %10.4f\n",
           V.name, V.nh, V.ni, V.nc, V.np, V.ns, V.sw, V.nf, V.dup, V.strb, t, med[0]);
  }
  return 0;
}
