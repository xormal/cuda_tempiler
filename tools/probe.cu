// ИЗМЕРИТЕЛЬ ВРЕМЕННЫХ ОТПЕЧАТКОВ (M2) для sm_70.
//
// ЧТО ЭТО. Стенд, который для ЗАДАННОЙ смеси команд выдаёт ПЕРИОД её повторения на железе, в
// тактах, прямым чтением clock64() вокруг нераскатанного цикла. Тело цикла -- это ровно тот
// объект, который в модели называется "множество атомов с отпечатками", а измеренный период --
// ровно T*, минимум которого ищет планировщик. Поэтому стенд меряет НЕ "скорость ядра", а
// величину, входящую в модель.
//
// ПОЧЕМУ ИМЕННО ТАК
//   * ЦИКЛ, а не прямая: период установившегося цикла -- это modulo-расписание, и компилятор
//     его строит сам; мы меряем результат его укладки, а не свою.
//   * clock64() НА ВАРП: мерить хостом бесполезно -- запуск ядра стоит больше тела.
//   * 1 БЛОК НА SM принудительно (64 КБ динамической разделяемой): иначе число варпов на
//     планировщик неизвестно, а §3b говорит, что оно и есть половина ответа.
//   * ВСЕ операнды приходят из памяти (маска m==0 читается из глобальной), поэтому ptxas не
//     может свернуть ни одной команды по значению; проверяется дампом SASS, а не доверием.
//
// ОСИ, КОТОРЫЕ ЭТОТ СТЕНД РАЗВОДИТ (то, чего не может статический счёт)
//   NH -- тензорных команд на итерацию   (канал "тензорный конвейер", tau тактов)
//   NI -- НЕЗАВИСИМЫХ целочисленных     (чистая нагрузка на порт выдачи, никто не ждёт)
//   NC -- ЦЕПОЧКА зависимых, питающая операнд тензорной команды (тот же счёт, другое МЕСТО)
//   NS -- обращений к разделяемой памяти шириной SW бит (канал MIO)
//   NF -- независимых FFMA (канал fp32-конвейера)
//   DUP -- сколько ПОЛОС читают ОДИН И ТОТ ЖЕ адрес (ось "модель адреса", п.9 README):
//          уникальных байт на обращение = 32/DUP * SW/8.  Если цена MIO зависит от ШИРИНЫ
//          команды, период не должен меняться; если от УНИКАЛЬНЫХ байт -- должен падать в DUP раз.
//          Это прямой фальсификатор нижней границы: сейчас модель берёт width*32 (худший случай).
//
// ОСЬ РЕГИСТРОВОГО ДАВЛЕНИЯ (п.8 README) отдельного параметра НЕ требует и получена так:
//   NP независимых цепей длины NC -> ровно NP значений, живых ЧЕРЕЗ ОБРАТНУЮ ДУГУ (MaxLive = NP),
//   при счёте команд NC*NP.  Две лестницы:
//     (а) NC=1, NP=8..240      -- давление растёт вместе с отпечатком (вычитается моделью);
//     (б) NC*NP = 192 = const  -- отпечаток по КАЖДОМУ каналу ФИКСИРОВАН, меняется только MaxLive.
//   Излом ищется на (а) двухсегментной подгонкой, проверяется на (б) и сверяется с LOCAL из
//   cuobjdump -res-usage (первое появление разлива).
//
// СБОРКА:  nvcc -arch=sm_70 -O3 -lineinfo -o probe probe.cu
// ЗАПУСК:  ./probe --warps 8 --iters 2000 [--only <substr>] [--exact]
