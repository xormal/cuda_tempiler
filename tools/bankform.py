# -*- coding: utf-8 -*-
"""ЗАКОН КОНФЛИКТНОСТИ БАНКОВ В ЗАМКНУТОМ ВИДЕ. Ноль GPU, ноль сборок, микросекунды.

    конфликтность = |R| / |{ r*S mod 32 : r in R }|

где `S` -- шаг строки В СЛОВАХ, а `R` -- множество СТРОК, которые несут полосы варпа в ОДНОЙ
команде (берётся из КАРТЫ ПОЛОС, а не из объявления массива).

ОТКУДА. Внутри одной команды варпа все индексы, кроме строки, одинаковы у всех полос, поэтому адрес
распадается на постоянную и одно линейное слагаемое: `bank = (const + r*S) mod 32`. Полосы с
ОДИНАКОВЫМ `r` читают один адрес -- это рассылка, и она бесплатна (замерено: 32/DUP, насыщения нет).
Конфликт дают только полосы с РАЗНЫМ `r`, попавшие в один банк. Значит конфликтность -- это
мощность прообраза, то есть свойство ПАРЫ (карта полос, шаг), а не шага.

ЧТО ЭТИМ ОПРОВЕРГНУТО. Прежнее правило «шаг кратен 32 словам -> конфликт» промахивается НА ОБОИХ
КОНЦАХ: S=4 не кратен 32 и даёт 2-кратный конфликт, S=8 не кратен и даёт 4-кратный. В боевых ядрах
оно промахнулось трижды: плитка K (шаг 68 слов) -- 74.5 % конфликтов ядра; накопитель эпилога
(шаг 130 слов) -- 89.9 %; и группа редукций ниже.

СВЕРКА. Формула проверена ПОЛНОЙ кривой перебора (13 точек, 33 сборки, 4 часа машинного времени):
три предсказанных уровня легли на замер с разбросом 0.46 / 0.02 / 0.00 п.п. -- см. `selftest`.

ГЛАВНОЕ ПРАКТИЧЕСКОЕ СЛЕДСТВИЕ. Перебор для этого класса не нужен: формула даёт ответ по всем
значениям дополнения мгновенно. Перебор превращается из ИСКАТЕЛЯ в ФАЛЬСИФИКАТОР формулы -- и в
этой роли он её и подтвердил.

ЗАПУСК:  python3 tools/bankform.py selftest
         python3 tools/bankform.py sweep --rows "(l&1)|((l&16)>>2)|(l&8)" --stride 4 --pad 0..12
"""

import argparse
import sys

BANKS = 32


def rows_from_lanemap(expr, nlanes=32):
    """Множество строк R по выражению от номера полосы `l`. Выражение -- только биты и арифметика."""
    allowed = set("l0123456789 ()&|^~<>+-*/%")
    if not set(expr) <= allowed:
        raise SystemExit(
            f"в выражении карты полос есть недопустимые символы: {sorted(set(expr) - allowed)}"
        )
    return sorted({eval(expr, {"__builtins__": {}}, {"l": l}) for l in range(nlanes)})


def conflictedness(rows, stride_words):
    """|R| / |образ R под умножением на S по модулю 32|."""
    image = {(r * stride_words) % BANKS for r in rows}
    return len(rows) / len(image), sorted(image)


def sweep(rows, base_stride, pads):
    out = []
    for pad in pads:
        S = base_stride + pad
        c, img = conflictedness(rows, S)
        out.append((pad, S, c, img))
    return out


# ------------------------------------------------------------------------------------------------
# САМОПРОВЕРКА НА ЗАМЕРЕ. Данные -- полная кривая перебора padsweep.py по ядру volta_fwd_ws
# (байтовый форвард d=256, KVFMT=8, B1/H4/Hkv1/S512, causal), массивы sRedM/sRedS.
# Карта полос из исходника volta_fwd_ws.cuh:692 -- rowbase = (lane&1) | ((lane&16)>>2) | (lane&8).
MEASURED = {
    0: 19.43,
    1: 15.58,
    2: 16.02,
    3: 15.58,
    4: 21.57,
    5: 15.58,
    6: 16.03,
    7: 15.58,
    8: 19.45,
    9: 15.57,
    10: 16.01,
    11: 15.58,
    12: 21.57,
}
LANEMAP_WS = "(l&1)|((l&16)>>2)|(l&8)"
WN = 4


def selftest():
    rows = rows_from_lanemap(LANEMAP_WS)
    print(f"карта полос: rowbase = {LANEMAP_WS}")
    print(
        f"строки R = {rows}   ({BANKS // len(rows)} полос на строку -> рассылка, бесплатна)\n"
    )
    print(
        f"{'pad':>4} | {'S':>3} | {'разных банков':>13} | {'конфликтность':>13} | {'ЗАМЕР %':>8}"
    )
    print("-" * 60)
    levels = {}
    for pad, S, c, img in sweep(rows, WN, sorted(MEASURED)):
        levels.setdefault(c, []).append(MEASURED[pad])
        print(
            f"{pad:>4} | {S:>3} | {len(img):>13} | {c:>13.0f} | {MEASURED[pad]:>8.2f}"
        )

    print("\nРАЗДЕЛЕНИЕ УРОВНЕЙ (главная проверка: уровни НЕ ДОЛЖНЫ пересекаться):")
    ok = True
    bounds = []
    for c in sorted(levels):
        v = levels[c]
        bounds.append((c, min(v), max(v)))
        print(
            f"  конфликтность {c:.0f}: замер {min(v):6.2f} .. {max(v):6.2f} %   "
            f"(разброс {max(v) - min(v):.2f} п.п., точек {len(v)})"
        )
    for i in range(len(bounds) - 1):
        if bounds[i][2] >= bounds[i + 1][1]:
            print(
                f"  !! ПЕРЕСЕЧЕНИЕ уровней {bounds[i][0]:.0f} и {bounds[i + 1][0]:.0f} -- формула не разделяет"
            )
            ok = False
    print(
        "\nСАМОПРОВЕРКА:",
        "ПРОЙДЕНА -- формула разделяет замеренные уровни" if ok else "ПРОВАЛЕНА",
    )

    print("\nЧТО ФОРМУЛА НЕ ОБЪЯСНЯЕТ (не сглаживать):")
    print(
        "  * разброс 0.46 п.п. внутри конфликтности 1: нечётные pad дают 15.58, чётные 16.0."
    )
    print(
        "    Вероятно, дополнение сдвигает БАЗЫ соседних массивов в разделяемом блоке, а доля"
    )
    print("    меряется по ВСЕМУ ядру. НЕ ПРОВЕРЕНО.")
    print(
        "  * свизл и XOR-адресация: отображение там не линейное, формула неприменима."
    )
    print(
        "    Накопитель эпилога cutlass (89.9 % конфликтов форварда) этим НЕ БЕРЁТСЯ."
    )
    print(
        "  * неоднородные карты полос: если строка зависит от полосы не через биты `lane`,"
    )
    print("    множество R надо брать ЗАМЕРОМ, а не разбором исходника.")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("selftest", help="сверить формулу с замеренной кривой")
    sp = sub.add_parser("sweep", help="конфликтность по всем дополнениям")
    sp.add_argument(
        "--rows", required=True, help="выражение rowbase от номера полосы `l`"
    )
    sp.add_argument(
        "--stride", type=int, required=True, help="базовый шаг строки В СЛОВАХ"
    )
    sp.add_argument("--pad", default="0..15", help="диапазон дополнений, напр. 0..15")
    a = ap.parse_args()

    if a.cmd == "selftest":
        return selftest()

    lo, hi = (int(x) for x in a.pad.split(".."))
    rows = rows_from_lanemap(a.rows)
    print(f"строки R = {rows}   ({BANKS // len(rows)} полос на строку -> рассылка)\n")
    print(f"{'pad':>4} | {'S':>4} | {'разных':>7} | {'конфликтность':>13} | образ")
    print("-" * 78)
    best = None
    for pad, S, c, img in sweep(rows, a.stride, range(lo, hi + 1)):
        print(f"{pad:>4} | {S:>4} | {len(img):>7} | {c:>13.2f} | {img}")
        if best is None or c < best[2]:
            best = (pad, S, c)
    print(f"\nМИНИМАЛЬНАЯ КОНФЛИКТНОСТЬ {best[2]:.2f} при pad={best[0]} (S={best[1]}).")
    print(
        "НО: минимум и ВЫБОР -- разные вещи. При равной конфликтности брать МЕНЬШЕЕ дополнение"
    )
    print("(замерено: pad=9 и pad=1 дают одно и то же, но +3456 Б против +384 Б).")
    print(
        "И проверить, что дополнение не сделало ХУЖЕ: одностороннее «дополнить, чтобы банки"
    )
    print(
        "разъехались» НЕВЕРНО -- в замеренной кривой pad=4 и 12 хуже базы (21.57 против 19.43)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
