# -*- coding: utf-8 -*-
"""ПОДСТАВНАЯ ЦЕЛЬ ДЛЯ САМОПРОВЕРКИ РЕЖИМА `time` -- КАРТА НЕ НУЖНА.

Изображает ядро с ИЗВЕСТНЫМ АНАЛИТИЧЕСКИ устройством, чтобы проверить не арифметику долей (её
проверяет `replay` на якоре §3b), а ВЕСЬ КОНВЕЙЕР режима `time`: разбор маски, сборку вариантов,
вариант "снять всё", пары и разложение невязки.

МОДЕЛЬ. Два канала плюс последовательный ПОЛ (пролог/эпилог/запуск -- работа, не принадлежащая
ни одной фазе):

    канал 1:  gemm1 = 40,  gemm2 = 20        (идут последовательно по одному каналу)
    канал 2:  softmax = 30                   (идёт ПАРАЛЛЕЛЬНО, целиком в тени gemm1)
    пол:      25                             (НЕ НАЗВАН ни одной фазой)

    время(маска) = 25 + max( сумма живых на канале 1 , сумма живых на канале 2 )

ЧЕГО ЖДЁМ (считается на бумаге, без инструмента):

    база          25 + max(60,30) = 85
    снят gemm1    25 + max(20,30) = 55   ->  доля 1-55/85 = 35.294 %
    снят gemm2    25 + max(40,30) = 65   ->  доля           23.529 %
    снят softmax  25 + max(60, 0) = 85   ->  доля            0.000 %   <-- СПРЯТАН ЦЕЛИКОМ
    снято ВСЁ     25                      ->  доля           70.588 %

    сумма одиночных  58.824 %
    ПЕРЕКРЫТИЕ       70.588 - 58.824 = 11.765 %   (ровно спрятанный softmax: 10/85)
    НЕНАЗВАННОЕ      1 - 70.588       = 29.412 %  (ровно пол: 25/85)

Смысл проверки: фаза softmax занята ПОЛНОСТЬЮ (30 из 85), а одиночное снятие даёт ей РОВНО НОЛЬ.
Инструмент обязан не потерять её, а вернуть в слагаемом ПЕРЕКРЫТИЕ; и обязан отдельно показать
пол, который не назван ни одной фазой. Это и есть та невязка 22.3 %, из-за которой всё писалось.
"""

import sys

FLOOR = 25.0
CH1 = [("gemm1", 0, 40.0), ("gemm2", 1, 20.0)]
CH2 = [("softmax", 2, 30.0)]


def model(mask):
    a = sum(c for _, i, c in CH1 if not (mask >> i) & 1)
    b = sum(c for _, i, c in CH2 if not (mask >> i) & 1)
    return FLOOR + max(a, b)


if __name__ == "__main__":
    print("%.9f" % model(int(sys.argv[1], 0)))
