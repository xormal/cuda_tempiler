def median_ratio(pairs):
    """Медиана ПОПАРНЫХ отношений.

    Почему не отношение медиан: плечи меряются в РАЗНЫЕ моменты, и дрейф частоты входит в
    каждое плечо по-своему. Парность его сокращает, отношение медиан -- нет.
    """
    vals = sorted(float(a) / float(b) for a, b in pairs if b)
    if not vals:
        return float("nan")
    n = len(vals)
    return vals[n // 2] if n % 2 else 0.5 * (vals[n // 2 - 1] + vals[n // 2])
